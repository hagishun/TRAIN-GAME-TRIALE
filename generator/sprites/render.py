"""3D描画・景色・対向列車のスプライト（ペンとスタンプで前面展望を描く）。"""
import assets
from routes_data import all_station_names, TRANSFER, AIRPORT_LAYOUT
from sb3 import *
from sprites.common import add_projection, add_colors, fog_amount, vis_height_at

# 3D描画スプライトの色番号（色を読み込む の順番）
COLOR_SLOTS = ['色_地面1', '色_地面2', '色_道床1', '色_道床2', '色_左外側', '色_右外側', '色_霧', '色_架線柱', '色_ホーム',
               '色_ホームの側面', '色_点字ブロック', '色_枕木', '色_レール', '色_架線', '色_空港の芝生', '色_エプロン', '色_滑走路',
               '色_高架', '色_側壁']
C = {n: i + 1 for i, n in enumerate(COLOR_SLOTS)}
FOG = C['色_霧']


def copy_list(a, b):
    """リスト a の中身をリスト b にうつすブロック。"""
    return [delete_all(b), set_('_i', 1), repeat(length(a), [add(b, item(a, V('_i'))), change('_i', 1)])]


def build_render(p):
    s = p.sprite('3D描画')
    s.costume_svg('ペン用', *assets.pen_canvas())
    s.costume_svg('駅名標', *assets.station_board(None))
    for name in all_station_names():
        s.costume_svg(name, *assets.station_board(name, TRANSFER.get(name)))
    for v in range(15, 355, 5):
        s.costume_svg(f'制限{v}', *assets.limit_sign(v))
    s.costume_svg('制限解除', *assets.limit_sign('解除'))
    for kind in ('夕方', '昼', '霧'):
        s.costume_svg(f'空_{kind}', assets.backdrop(kind), 240, 180)
    s.costume_svg('停目', *assets.stop_marker('停'))
    for n in (1, 2, 3):
        s.costume_svg(f'番線{n}', *assets.track_number_sign(n))
    for n in (2, 4, 6, 8, 10):
        s.costume_svg(f'停目{n}', *assets.stop_marker(n))
    s.overview = ('【3D描画スプライト】ペンで地面・枕木・レール・ホーム・架線柱・架線を描き、標識と駅名標をスタンプする。\n'
                  '■ しくみ: 画面の下から地平線まで、横線（行）を何本も引いて地面を作る。1 本ごとに「その行が何 m 先か」が\n'
                  '   決まっているので、準備のときに表（行z など）にしておき、毎フレームはカーブでずれる分だけ計算する。\n'
                  '   前方 z m の物は、地平線から「目の高さ × 焦点距離 ÷ z」ピクセル下に見える（遠いほど地平線に近い）。\n'
                  '■ カーブ: 10m ごとの曲率表を 2 回足し合わせて、前方の線路がどれだけ横にずれるか（横ずれ表）を作る。\n'
                  '■ 注意: ペンの絵はすべてのスプライトより下（奥）に描かれる。運転台や計器はスプライトなので手前に出る。\n'
                  '■ 駅名標: 駅名と同じ名前のコスチュームがあれば、その絵がホームに立つ（無ければ無地の「駅名標」）。\n'
                  '   駅名を変えたら、ここのコスチュームの名前と文字も変えると駅名標も変わる。\n'
                  '■ 標識: 「制限60」のような名前のコスチュームを使う（15〜350 の 5 きざみ）。番線の表示は「番線1」〜「番線3」。\n'
                  '■ 3D の物の絵は「20 ピクセル ＝ 1 m」で描き、回転中心を根元（下の真ん中）にする。\n'
                  '■ 高架: 高架が見える所（「高架モード」が 1）では、いまいる所の線路の高さ（「今の高さ」）だけ目が高くなるので、\n'
                  '   地面は同じ行でも遠くが見える（下に見える）。線路は「高さずれ表」から、画面の行ごとに何 m 先が見えるかを\n'
                  '   さがして描く（坂の先は上がって・下がって見え、坂の頂上の向こうはかくれる）。高架の床と側壁もここで描く。\n'
                  '   高架モードのときは、線路と高架を景色（建物）のあと（描画3）に描く。高架より下の建物を上からかくすため。\n'
                  '■ 景色の切り替え: 「景色の境目」より先は次の景色の色、手前は「前の〜色表」で描く。空は「空_昼」などの\n'
                  '   コスチュームを「景色の混ぜ具合」だけ重ねて、少しずつ次の空にする。\n'
                  '■ 駅の配線（3番線まで）: 駅の手前で分岐器から副本線（3番線）が左に分かれ、駅の先でまた合わさる。\n'
                  '   『配線を調べる』が近くの駅（「配線の駅」）を見つけ、『副本線の横』が道のりごとの副本線の横の位置を出す。\n'
                  '   電車が副本線に入るとき（「進路」が 1）は、カメラ（運転席）も副本線にそってずれる（「自分の横」）。\n'
                  '   ホームは「ホームの表」（線路側の端・外側の端・どの線路のホームか）を見て描く。\n'
                  '   ホームの端にロープ柵などを描き足すときは、『駅のホームを描く』の中の、ホームを 1 つ描いたあとに足すとよい。')
    for n in ('行の数', 'HF', '_d', '_z', '_s', '_X', '_cx', '_y', '_st', '_x1', '_x2', '_i', '_j', '_k', '_n', '_f',
              '_tz', '_ts', '_a', '_b', '_dX', '比', '枕木の色', 'レールの色', '架線の色', '端', '外', '向き', 'zs', 'ze',
              '_o', '_w', '_e1', '_e2', '_g', '_kg', '_zg', '_d0', '_D', '_N', '_ra', '_dr', '_q', '_t', '_zt', '_h', '_走', '_m', '_c',
              '線路行の数', '副本線x', '_bt', '進路', '自分の傾き', '_p', '_前副', '_hk', '_he', '_ho', '_hn'):
        s.var(n, 0)
    for n in ('行z', '行y', '行s', '行j', '行f', '行中心x', '行tz', '行ts', '行tj', '行tf', '地面色表', '道床色表',
              '左外側色表', '右外側色表', 'ホーム色表', 'ホーム側面色表', '点字色表', 'レール太さ', '標識の位置',
              '標識の名前', '線z', '線s', '線j', '線f', '線x', '空港芝生色表', 'エプロン色表', '滑走路色表',
              '高架色表', '側壁色表', '前の地面色表', '前の道床色表', '前の左外側色表', '前の右外側色表', '前の高架色表',
              '前の側壁色表', '高さずれ表', '深さ表', '線路行D', '線路行z', '線路行r', '線路行s', '線路行x', '線路行y',
              '線路行c', '線路行旧', '線上げ', '線隠れY', '行副', '線副', '線路行副', 'ホームの線路側', 'ホームの外側', 'ホームの線'):
        s.lst(n)
    add_projection(s, ground_flag=True)
    add_colors(s, FOG)

    # ---------------------------------------------------------------- 準備
    s.script(when_recv('描画の準備'), [call('描画の準備をする')], comment='路線を読み込んだあとに 1 回だけ届く')
    s.proc('描画の準備をする', [], [
        hide(), costume('ペン用'), set_size(100), clear_effects(), pen_up(),
        call('色を読み込む'),
        call('行を作る'),
        call('架線の点を作る'),
        call('標識を作る'),
        call('線路の行を作る'),
        delete_all('横ずれ表'), delete_all('高さずれ表'), delete_all('深さ表'), delete_all('隠れ表'),
        repeat(floor(V('最大描画距離') / 10) + 3, [add('横ずれ表', 0), add('高さずれ表', 0), add('深さ表', 0),
                                                  add('隠れ表', -9999)]),
        set_('高架モード', 0), set_('今の高さ', 0),
    ], comment='色・行・架線の点・標識の表を作る')
    s.proc('色を読み込む', [], [
        delete_all('色R'), delete_all('色G'), delete_all('色B'),
    ] + [call('色を追加 %s', V(n)).c(f'{i + 1}番の色') if i in (0, 6) else call('色を追加 %s', V(n))
         for i, n in enumerate(COLOR_SLOTS)] + [
        call('霧の色を混ぜる 色番号 %s 霧の濃さ %s', C['色_枕木'], 0), set_('枕木の色', V('混ぜた色')),
        call('霧の色を混ぜる 色番号 %s 霧の濃さ %s', C['色_レール'], 0), set_('レールの色', V('混ぜた色')),
        call('霧の色を混ぜる 色番号 %s 霧の濃さ %s', C['色_架線'], 0.15), set_('架線の色', V('混ぜた色')),
    ], comment='路線と設定の色（#rrggbb）を、計算できる赤・緑・青の数にする。順番が色番号になる:\n'
               + '、'.join(f'{i + 1}={n[2:]}' for i, n in enumerate(COLOR_SLOTS)))

    def row_color(table, n1, n2=None, far_same=False):
        if n2 is None:
            return [call('霧の色を混ぜる 色番号 %s 霧の濃さ %s', n1, V('_f')), add(table, V('混ぜた色'))]
        return [
            call('霧の色を混ぜる 色番号 %s 霧の濃さ %s', n1, V('_f')), add(table, V('混ぜた色')),
            if_(V('_z') < V('縞を描く距離'), [call('霧の色を混ぜる 色番号 %s 霧の濃さ %s', n2, V('_f'))]),
            add(table, V('混ぜた色')).c('縞の2色目（遠くは1色目と同じにして縞を消す）'),
        ]

    s.proc('行を作る', [], [
        delete_all('行z'), delete_all('行y'), delete_all('行s'), delete_all('行j'), delete_all('行f'),
        delete_all('行中心x'), delete_all('行tz'), delete_all('行ts'), delete_all('行tj'), delete_all('行tf'),
        delete_all('地面色表'), delete_all('道床色表'), delete_all('左外側色表'), delete_all('右外側色表'),
        delete_all('ホーム色表'), delete_all('ホーム側面色表'), delete_all('点字色表'), delete_all('レール太さ'),
        delete_all('空港芝生色表'), delete_all('エプロン色表'), delete_all('滑走路色表'),
        delete_all('高架色表'), delete_all('側壁色表'), delete_all('行副'),
        set_('HF', V('目の高さ') * V('焦点距離')),
        set_('比', (V('目の高さ') - V('ホームの高さ')) / V('目の高さ'))
        .c('同じ画面の行に見えるホームの床は、地面より「比」倍だけ近い'),
        set_('_d', V('地平線Y') - V('運転台の上端Y') - V('行の間隔') / 2).c('いちばん下の行が地平線から何ピクセル下か'),
        repeat_until(V('_d') < V('HF') / V('最大描画距離'), [
            set_('_z', V('HF') / V('_d')).c('この行に見える地面は何 m 先か（地平線に近いほど遠い）'),
            add('行z', V('_z')),
            add('行y', V('地平線Y') - V('_d')),
            add('行s', V('焦点距離') / V('_z')),
            add('行j', floor(V('_z') / 10) + 1),
            add('行f', V('_z') / 10 - floor(V('_z') / 10)),
            add('行中心x', 0).c('この行での線路の中心の x（カーブで毎フレーム変わる。『地面と道床を描く』で入れる）'),
            add('行副', 'なし').c('この行での副本線の横の位置（駅の近くだけ。『地面と道床を描く』で入れる）'),
            set_('_tz', V('_z') * V('比')),
            add('行tz', V('_tz')),
            add('行ts', V('焦点距離') / V('_tz')),
            add('行tj', floor(V('_tz') / 10) + 1),
            add('行tf', V('_tz') / 10 - floor(V('_tz') / 10)),
            set_('_f', fog_amount(V('_z'))).c('遠いほど霧が濃い（0〜1）'),
        ] + row_color('地面色表', C['色_地面1'], C['色_地面2']) + row_color('道床色表', C['色_道床1'], C['色_道床2'])
          + row_color('左外側色表', C['色_左外側']) + row_color('右外側色表', C['色_右外側'])
          + row_color('ホーム側面色表', C['色_ホームの側面']) + row_color('空港芝生色表', C['色_空港の芝生'])
          + row_color('エプロン色表', C['色_エプロン']) + row_color('滑走路色表', C['色_滑走路'])
          + row_color('高架色表', C['色_高架']) + row_color('側壁色表', C['色_側壁']) + [
            set_('_f', fog_amount(V('_tz'))),
        ] + row_color('ホーム色表', C['色_ホーム']) + row_color('点字色表', C['色_点字ブロック']) + [
            if_else(V('焦点距離') / V('_z') * 0.075 > 0.9, [add('レール太さ', V('焦点距離') / V('_z') * 0.075)],
                    [add('レール太さ', 0.9)]).c('レールの頭の幅は約 7.5cm'),
            change('_d', 0 - V('行の間隔')),
        ]),
        set_('行の数', length('行z')),
    ], comment='【地面の行の表】画面の下から地平線に向かって「行の間隔」ピクセルごとに、\n'
               'その行の前方距離 z・画面の y・倍率・霧をかけた色などを計算しておく')
    s.proc('架線の点を作る', [], [
        delete_all('線z'), delete_all('線s'), delete_all('線j'), delete_all('線f'), delete_all('線x'), delete_all('線上げ'),
        delete_all('線隠れY'), delete_all('線副'),
        set_('_z', 3),
        repeat_until(V('_z') > V('最大描画距離'), [
            add('線z', V('_z')), add('線s', V('焦点距離') / V('_z')), add('線j', floor(V('_z') / 10) + 1),
            add('線f', V('_z') / 10 - floor(V('_z') / 10)), add('線x', 0), add('線上げ', 0), add('線隠れY', -9999), add('線副', 'なし'),
            set_('_z', V('_z') * 1.12 + 0.6).c('近くは細かく、遠くはまばらに点を置く'),
        ]),
    ], comment='架線（電線）を折れ線で描くための点の距離の表')
    s.proc('標識を作る', [], [
        delete_all('標識の位置'), delete_all('標識の名前'),
        set_('_i', 1),
        repeat(length('制限の開始'), [
            add('標識の位置', item('制限の開始', V('_i'))),
            add('標識の名前', join('制限', item('制限の速度', V('_i')))).c('コスチューム名「制限60」など'),
            add('標識の位置', item('制限の終了', V('_i'))),
            add('標識の名前', '制限解除'),
            change('_i', 1),
        ]),
    ], comment='速度制限の始めと終わりに立てる標識の表を作る')
    s.script(when_recv('景色が変わった'), [call('前の景色の色をとっておく'), call('色を読み込む'), call('行を作る')],
             comment='次の景色を読み込んだら、いまの色の表を「前の〜」にとっておいて、地面・外側・霧の色の表を作り直す')
    s.proc('前の景色の色をとっておく', [], sum((copy_list(a, '前の' + a) for a in ('地面色表', '道床色表', '左外側色表', '右外側色表',
                                                                           '高架色表', '側壁色表')), []),
           comment='「景色の境目」より手前は、前の景色の色で描くので、色の表をうつしておく')
    s.script(when_recv('標識を作り直す'), [call('標識を作る')],
             comment='アクシデント（強風・大雨）で速度制限が増えたときに、標識の表を作り直す')

    # ---------------------------------------------------------------- 毎フレーム
    s.script(when_recv('描画1_地面'), [call('地面を描く')], comment='毎フレーム 1 番目の描画')
    s.proc('地面を描く', [], [
        pen_clear().c('前のフレームの絵を消す'),
        call('配線を調べる'),
        call('高さを調べる'),
        call('空を混ぜる'),
        call('横ずれ表を作る'),
        if_else(eq(V('高架モード'), 1), [
            call('高さずれ表を作る'),
            call('線路の行を計算'),
            call('高架から地面を描く'),
            call('空港の灯りを描く'),
        ], [
            call('地面と道床を描く'),
            call('空港の灯りを描く'),
            call('枕木を描く'),
            call('レールを描く'),
        ]).c('高架が見えるときは、地面だけ描く（線路と高架は、建物を描いたあとの描画3で描く）'),
    ], comment='地面・空港の灯り・枕木・レールを描く')
    s.proc('高さを調べる', [], [
        set_('今の高さ', vis_height_at(V('位置'))).c('いまいる所の線路の、地面からの高さ [m]（高架の上なら 0 より大きい。\n'
                                                    '設定の「見た目の高さの強さ」倍にして描く）'),
        set_('高架モード', 0),
        set_('_g', 1),
        repeat(length('高架の開始'), [
            if_(and_(item('高架の開始', V('_g')) < V('位置') + V('最大描画距離') + 20, item('高架の終了', V('_g')) > V('位置') - 20),
                [set_('高架モード', 1)]),
            change('_g', 1),
        ]).c('見える範囲に高架があれば「高架モード」を 1 にする（高架のない路線はいつも 0 で、ふつうの描き方）'),
    ], comment='いまの線路の高さと、高架が見えるかを調べる')
    s.proc('空を混ぜる', [], [
        if_(and_(V('景色の混ぜ具合') > 0, not_(eq(V('前の空'), V('空')))), [
            costume(join('空_', V('空'))),
            set_size(100),
            set_effect('GHOST', (1 - V('景色の混ぜ具合')) * 100).c('混ぜ具合 0 で見えない、1 で次の空だけになる'),
            goto(0, 0),
            stamp(),
            clear_effects(),
            costume('ペン用'),
        ]),
    ], comment='景色の変わり目に近づいたら、背景（前の空）の上に、次の空を少しずつ濃く重ねる')
    s.proc('配線を調べる', [], [
        set_('配線の駅', 0), set_('配線の始め', -99999), set_('配線の終わり', -99999),
        set_('進路', 0), set_('自分の横', 0), set_('自分の傾き', 0),
        set_('_hk', 1),
        repeat(length('駅の分岐の始め'), [
            if_(and_(eq(V('配線の駅'), 0), item('駅の分岐の終わり', V('_hk')) > V('位置'),
                     item('駅の分岐の始め', V('_hk')) < V('位置') + V('最大描画距離') + 20), [set_('配線の駅', V('_hk'))]),
            change('_hk', 1),
        ]).c('まだ通り過ぎていない駅のうち、分岐器が見えるいちばん手前の駅（無ければ 0）'),
        if_(V('配線の駅') > 0, [
            set_('配線の始め', item('駅の分岐の始め', V('配線の駅'))),
            set_('配線の終わり', item('駅の分岐の終わり', V('配線の駅'))),
            if_(and_(eq(item('駅の種別', V('配線の駅')), '停車'),
                     eq(item('駅の着く番線', V('配線の駅')), item('駅の副本線の番号', V('配線の駅')))), [set_('進路', 1)])
            .c('今日この駅で副本線に着くなら、電車は分岐器で曲がって副本線を走る（通過する駅はいつも本線）'),
            if_(eq(V('進路'), 1), [
                call('副本線の横 %s m', V('位置')),
                if_(not_(eq(V('副本線x'), 'なし')), [
                    set_('自分の横', V('副本線x')),
                    if_(V('位置') < V('配線の始め') + V('分岐の長さ'), [
                        set_('自分の傾き', V('副本線の横') * 6 * V('_bt') * (1 - V('_bt')) / V('分岐の長さ')),
                    ]),
                    if_(V('位置') > V('配線の終わり') - V('分岐の長さ'), [
                        set_('自分の傾き', 0 - V('副本線の横') * 6 * V('_bt') * (1 - V('_bt')) / V('分岐の長さ')),
                    ]),
                ]).c('いまいる所の副本線の横の位置と、向き（傾き）。カメラ（運転席）がそのぶん横にずれて、向きも変わる'),
            ]),
        ]),
    ], comment='【駅の配線】近くの駅（「配線の駅」）と、その駅の分岐器の場所（「配線の始め」〜「配線の終わり」）を調べる。\n'
               '電車が副本線に入るとき（「進路」が 1）は、電車のいる所の副本線の横の位置を「自分の横」に入れる')
