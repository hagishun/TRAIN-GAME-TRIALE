    for n in ('有無', '動き', '前後', '横', '高さ', '速さ', '会社', '接地点', 'タイマー', '最初の着陸済'):
        s.var(f'飛行機の{n}' if n not in ('接地点', 'タイマー', '最初の着陸済') else f'飛行機_{n}', 0)
