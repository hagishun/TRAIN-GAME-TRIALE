"""複数のスプライトで同じ形のカスタムブロックを使うための部品。

Scratch のカスタムブロックはスプライトごとにしか使えないので、
同じ計算（3D の位置の計算・色の変換）を必要なスプライトにそれぞれ入れている。
"""
from sb3 import *


def height_at(pos):
    """高さ表から、道のり pos [m] での線路の地面からの高さ [m]（10m ごとの値のあいだは直線で補う）を求める式。"""
    c = floor(pos / 10) + 1
    return item('高さ表', c) + (item('高さ表', c + 1) - item('高さ表', c)) * (pos / 10 - floor(pos / 10))


def vis_height_at(pos):
    """画面に描くときの線路の高さ [m]（設定の「見た目の高さの強さ」倍）。"""
    return height_at(pos) * V('見た目の高さの強さ')


def add_projection(s, ground=False, ground_flag=False):
    """『位置を計算』: 前方 z m・横 m・高さ m の点が画面のどこに見えるかを計算する。

    ground=True のスプライト（景色）は、物を地面に置く（高架の上からは下に見える）。
    それ以外は線路の上に置く（高架の上では線路といっしょに高くなる）。
    ground_flag=True なら、変数「_地面」が 1 のあいだだけ地面に置く。
    """
    for n in ('画面x', '画面y', '倍率', '計算したX', '_pj', '_上げ', '_pw', '隠れ', '隠れY'):
        s.var(n, 0)
    if ground_flag:
        s.var('_地面', 0)
    on_ground = [set_('_上げ', 0 - V('今の高さ')).c('地面に置く物: 高架の上にいるときは、そのぶん下に見える')]
    on_track = [
        if_else(eq(V('高架モード'), 1), [
            set_('_pw', V('位置') + A('z')),
            set_('_上げ', vis_height_at(V('_pw')) - V('今の高さ'))
            .c('線路の上の物: その場所の線路の高さ − いまいる所の線路の高さ（上り坂の先は高く、下り坂の先は低く見える）'),
        ], [set_('_上げ', 0)]),
    ]
    if ground:
        lift = on_ground
    elif ground_flag:
        lift = [if_else(eq(V('_地面'), 1), on_ground, on_track)]
    else:
        lift = on_track
    hidden = [] if ground else [
        set_('隠れ', 0),
        set_('隠れY', -9999),
        if_(eq(V('高架モード'), 1), [
            set_('_pj', V('_pj') + 2).c('z より手前の線路（隠れ表のこの番号まで）が、この点の根元をかくすか'),
            if_(V('_pj') > length('隠れ表'), [set_('_pj', length('隠れ表'))]),
            set_('隠れY', item('隠れ表', V('_pj')) - 0.5).c('これより下（画面の y が小さい所）は手前の線路にかくれる'),
            if_(V('地平線Y') + (V('_上げ') - V('目の高さ')) * V('倍率') < V('隠れY'), [set_('隠れ', 1)]),
        ]).c('坂の頂上の向こうで、根元が手前の線路にかくれているときは「隠れ」を 1 にする（描かない）'),
    ]
    s.proc('位置を計算 前に %s m 横 %s m 高さ %s m', ['z', '横', '高さ'], [
        set_('_pj', floor(A('z') / 10)).c('横ずれ表は 10m ごとなので、z が何番目のあいだにあるかを求める'),
        if_else(V('_pj') > length('横ずれ表') - 2, [
            set_('計算したX', item('横ずれ表', length('横ずれ表'))),
        ], [
            set_('計算したX', item('横ずれ表', V('_pj') + 1) + (item('横ずれ表', V('_pj') + 2) - item('横ずれ表', V('_pj') + 1))
                 * (A('z') / 10 - V('_pj'))).c('となりの2つの値のあいだを直線で補う（線形補間）'),
        ]),
        set_('倍率', V('焦点距離') / A('z')).c('1m が画面で何ピクセルに見えるか。遠いほど小さい'),
        set_('画面x', (V('計算したX') + A('横') - V('運転席の横位置')) * V('倍率')),
    ] + lift + [
        set_('画面y', V('地平線Y') + (A('高さ') - V('目の高さ') + V('_上げ')) * V('倍率'))
        .c('目の高さより低い物は地平線より下に見える'),
    ] + hidden, comment='【3D の基本】前方 z m、線路の中心から横 m（右が＋）、高さ m の点を画面の座標にする。\n'
                        '結果は「画面x」「画面y」と、1m が何ピクセルかを表す「倍率」に入る。\n'
                        'カーブで線路がずれる分は 3D描画スプライトが毎フレーム作る「横ずれ表」から読む。\n'
                        '高架の近く（「高架モード」が 1）では、線路の高さのちがいの分（「_上げ」[m]）だけ上下にずらす'
                        + ('。\nこのスプライトの物はぜんぶ地面に置く' if ground else ''))


def add_colors(s, fog_index):
    """『色を追加』（#rrggbb → 赤・緑・青のリスト）と『霧の色を混ぜる』。"""
    for n in ('_値', '_桁', '混ぜた色'):
        s.var(n, 0)
    for n in ('色R', '色G', '色B'):
        s.lst(n)
    s.proc('色を追加 %s', ['16進数の色'], [
        set_('_値', 0),
        set_('_桁', 2),
        repeat(6, [
            set_('_値', V('_値') * 16 + index_of('16進数', letter_of(V('_桁'), A('16進数の色'))) - 1)
            .c('1文字ずつ 0〜15 の数にして 16 倍しながら足していく'),
            change('_桁', 1),
        ]),
        add('色R', floor(V('_値') / 65536)),
        add('色G', floor(V('_値') / 256) % 256),
        add('色B', V('_値') % 256),
    ], comment='"#5a8a3c" のような色の文字を、赤・緑・青（0〜255）に分けてリスト「色R」「色G」「色B」の最後に足す。\n'
               '色の番号はリストに足した順番になる。')
    fr, fg, fb = (item(l, fog_index) for l in ('色R', '色G', '色B'))
    s.proc('霧の色を混ぜる 色番号 %s 霧の濃さ %s', ['番号', '濃さ'], [
        set_('混ぜた色',
             round_(item('色R', A('番号')) + (fr - item('色R', A('番号'))) * A('濃さ')) * 65536
             + round_(item('色G', A('番号')) + (fg - item('色G', A('番号'))) * A('濃さ')) * 256
             + round_(item('色B', A('番号')) + (fb - item('色B', A('番号'))) * A('濃さ')))
        .c('ペンの色は「赤×65536＋緑×256＋青」の数でも指定できる'),
    ], comment=f'色番号の色に、霧の色（{fog_index}番）を「霧の濃さ」（0〜1）だけ混ぜて「混ぜた色」に入れる。\n'
               '遠くの物ほど霧の色に近づくので、奥行きが出る。')


def fog_amount(z):
    """霧の濃さ = 1 − e^(−z / 霧の距離)"""
    return 1 - exp_(0 - z / V('霧の距離'))
