        if_else(length('車両一覧') > 1, [set_('場面', '車両選択')] + menu('車両一覧', '車両番号', '車両メニューを表示'),
                [set_('車両番号', 1)]).c('車両が 1 種類のときは選ばずに 1 番にする'),
