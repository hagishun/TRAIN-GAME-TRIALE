    s.proc('路線を選ぶ', [], [set_('場面', '路線選択')] + menu('路線一覧', '路線番号', '路線メニューを表示'),
           warp=False, comment='路線一覧を見せて、路線のボタンのタップか数字キーで路線を選ぶ')
