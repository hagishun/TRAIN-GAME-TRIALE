"""運転（物理）・採点・ゲーム進行のスプライト。"""
import assets
from sb3 import *


def build_drive(p):
    s = p.sprite('運転')
    s.costume_svg('運転', *assets.icon('運転', '#2f9a4a'))
    s.overview = ('【運転スプライト】キー入力・ノッチ・加速とブレーキの計算・ATS・制限速度を担当。\n'
                  '毎フレーム「物理」を受け取ると『1フレーム進める』を実行します。\n'
                  '■ 操作: ↑（W）= 力行側へ / ↓（S）= ブレーキ側へ / スペース = 非常ブレーキ / H = 警笛\n'
                  '   画面の「力行」「ブレーキ」「非常」「警笛」ボタンのタップ（クリック）でも同じことができる（『ボタン入力を読む』）。\n'
                  '■ T25000系は最高 350km/h。止まるまで何 km もかかるので、TIMS の「あと」「予告」と案内を見て早めにブレーキ。\n'
                  '■ ノッチ: 変数「ノッチ」は 5〜1 が P5〜P1（力行）、0 が N、−1〜−8 が B1〜B8、−9 が EB（非常）。\n'
                  '■ 速度は km/h、加速度は km/h/s で計算しています。\n'
                  '■ 改造のヒント: キー操作を変えたいときは『キー入力を読む』、ブレーキの効き方を変えたいときは\n'
                  '   車両データスプライトの数値か『力とブレーキを計算する』を見てください。')
    for n in ('上キー前回', '下キー前回', '上キー時間', '下キー時間', '警笛キー前回', '力行目標', 'ブレーキ目標', '加速度',
              '前の速度', 'ジョイント番号', '力行加速度', 'ブレーキ減速度', '抵抗', '勾配加速度', '曲率', '_i', '割合',
              'ATS復帰の時間', '前のノッチ', '_c', '_d', '_a', '案内の段階', '処理した回数', 'ボタンの時間', '見た目の曲率'):
        s.var(n, 0)

    s.script(when_recv('運転の準備'), [call('運転の準備をする')], comment='路線を選んで運転を始めるときに呼ばれる')
    s.proc('運転の準備をする', [], [
        set_('位置', item('駅の位置', 1)).c('始発駅の停止位置から出発'),
        set_('速度', 0),
        set_('ノッチ', -8).c('止まっているときは B8（ブレーキいっぱい）にしておく'),
        call('ノッチ名を決める'),
        set_('ブレーキ率', 1), set_('力行率', 0), set_('BC圧', 440),
        set_('ATS状態', 0).c('0=ふつう 1=警報（ベル） 2=非常ブレーキ'),
        set_('方位', 0), set_('停車した', 0), set_('停止時の減速度', 0),
        set_('ドア', '開'), set_('次の駅番号', 2),
        repeat_until(or_(eq(item('駅の種別', V('次の駅番号')), '停車'), not_(V('次の駅番号') < length('駅名'))), [
            change('次の駅番号', 1),
        ]).c('通過駅をとばして、最初に止まる駅を「次の駅」にする'),
        set_('時刻の秒', item('駅の時刻秒', 1) - 20).c('発車時刻の 20 秒前から始める'),
        set_('ジョイント番号', floor(V('位置') / 25)),
        set_('上キー前回', 0), set_('下キー前回', 0), set_('警笛キー前回', 0),
        set_('処理した回数', V('ボタンを押した回数')).c('運転を始める前に押したボタンは数えない'),
        call('制限を調べる'),
    ], comment='運転を始める前に、電車の状態を始発駅に止まっている状態にする')

    s.script(when_recv('物理'), [call('1フレーム進める')], comment='ゲーム進行スプライトから毎フレーム届く')
    s.proc('1フレーム進める', [], [
        set_('停車した', 0).c('このフレームで止まったら 1 になる（採点スプライトが見る）'),
        call('キー入力を読む'),
        call('力とブレーキを計算する'),
        call('速度と位置を進める'),
        call('制限を調べる'),
        call('ATSを確かめる'),
        call('ブレーキの案内'),
        change('時刻の秒', V('Δt') * V('時間の速さ')).c('時計を進める。Δt は前のフレームからの秒数'),
        call('音のきっかけ'),
    ], comment='1 フレーム分の運転の計算。「画面を再描画せずに実行する」にしてあるので一瞬で終わる')

    def key_block(keys, prev, held, direction):
        cond = or_(*[key(k) for k in keys])
        return if_else(cond, [
            if_else(eq(V(prev), 0), [
                call('ノッチを動かす %s', direction),
                set_(held, 0),
                set_(prev, 1),
            ], [
                change(held, V('Δt')),
                if_(V(held) > 0.45, [call('ノッチを動かす %s', direction), set_(held, 0.3)])
                .c('押しっぱなしにすると 0.15 秒ごとに 1 段ずつ動く'),
            ]),
        ], [set_(prev, 0)])

    s.proc('キー入力を読む', [], [
        key_block(['up arrow', 'w'], '上キー前回', '上キー時間', 1).c('↑ または W: 力行側へ 1 段'),
        key_block(['down arrow', 's'], '下キー前回', '下キー時間', -1).c('↓ または S: ブレーキ側へ 1 段'),
        if_(key('space'), [call('非常ブレーキをかける')]).c('スペース: 非常ブレーキ（EB）。走行中に使うと減点'),
        if_else(key('h'), [
            if_(eq(V('警笛キー前回'), 0), [broadcast('警笛'), set_('警笛キー前回', 1)]),
        ], [set_('警笛キー前回', 0)]).c('H: 警笛'),
        call('ボタン入力を読む'),
    ], comment='キーを押した瞬間にノッチを 1 段動かす。「前回」の変数で押しっぱなしと区別している。\n'
               '最後に画面のボタン（タッチボタンスプライト）も読む')
    s.proc('ボタン入力を読む', [], [
        if_else(V('ボタンを押した回数') > V('処理した回数'), [
            set_('処理した回数', V('ボタンを押した回数')),
            set_('ボタンの時間', 0),
            if_(eq(V('押したボタン'), '力行'), [call('ノッチを動かす %s', 1)]),
            if_(eq(V('押したボタン'), 'ブレーキ'), [call('ノッチを動かす %s', -1)]),
            if_(eq(V('押したボタン'), '非常'), [call('非常ブレーキをかける')]),
            if_(eq(V('押したボタン'), '警笛'), [broadcast('警笛')]),
        ], [
            if_(or_(eq(V('押しているボタン'), '力行'), eq(V('押しているボタン'), 'ブレーキ')), [
                change('ボタンの時間', V('Δt')),
                if_(V('ボタンの時間') > V('ボタン_連続の待ち'), [
                    set_('ボタンの時間', V('ボタン_連続の待ち') - V('ボタン_連続の間隔')),
                    if_else(eq(V('押しているボタン'), '力行'), [call('ノッチを動かす %s', 1)],
                            [call('ノッチを動かす %s', -1)]),
                ]).c('押し続けると「ボタン_連続の待ち」秒たってから「ボタン_連続の間隔」秒ごとに 1 段（設定）'),
            ]),
        ]).c('新しく押されたボタンは 1 回だけ動かす（回数で数えるので短いタップも見のがさない）'),
    ], comment='【タッチ操作】画面のボタン（タッチボタンスプライト）が押されたら、キーと同じようにノッチなどを動かす。\n'
               '1 回タップで 1 段。押し続けると、キーよりゆっくり 1 段ずつ動く（動きすぎないように）')
    s.proc('非常ブレーキをかける', [], [
        if_(not_(eq(V('ノッチ'), -9)), [
            set_('前のノッチ', V('ノッチ')),
            set_('ノッチ', -9),
            call('ノッチ名を決める'),
            call('非常ブレーキを数える'),
        ]),
    ], comment='ノッチを EB（非常）にする。スペースキーと「非常」ボタン')

    s.proc('ノッチを動かす %s', ['向き'], [
        set_('前のノッチ', V('ノッチ')),
        change('ノッチ', A('向き')),
        if_(V('ノッチ') > 5, [set_('ノッチ', 5)]).c('P5 より上はない'),
        if_(V('ノッチ') < -9, [set_('ノッチ', -9)]).c('EB より下はない'),
        if_(and_(eq(V('ノッチ'), -9), not_(eq(V('前のノッチ'), -9))), [call('非常ブレーキを数える')]),
        if_(and_(V('前のノッチ') < 0, not_(V('ノッチ') < 0), V('速度') < 1), [broadcast('ブレーキ緩め')])
        .c('止まっているときにブレーキを緩めると「プシュー」'),
        call('ノッチ名を決める'),
    ], comment='ノッチを 1 段動かす（向き 1 = 力行側、−1 = ブレーキ側）')
    s.proc('ノッチ名を決める', [], [
        set_('ノッチ名', item('ノッチの名前', 6 - V('ノッチ'))).c('ノッチ 5 → 1番目 "P5"、0 → 6番目 "N"、−9 → 15番目 "EB"'),
    ], comment='ノッチの数を "P3" や "B5" のような表示用の名前にする')
    s.proc('非常ブレーキを数える', [], [
        if_(V('速度') > 3, [
            change('非常ブレーキ回数', 1),
            change('区間の減点', V('減点_非常ブレーキ')),
            set_('案内', join('非常ブレーキを使いました（減点 ', V('減点_非常ブレーキ'), '）')),
        ]),
    ], comment='走っているときに EB を使ったら減点（止まっているときは減点しない）。減点は設定の「減点_非常ブレーキ」')

    s.proc('力とブレーキを計算する', [], [
        if_else(and_(V('ノッチ') > 0, eq(V('ドア'), '閉'), V('ATS状態') < 2),
                [set_('力行目標', V('ノッチ') / 5)], [set_('力行目標', 0)])
        .c('ドアが開いているときと ATS 非常のときは力行できない'),
        set_('割合', V('Δt') / V('力行の遅れ')),
        if_(V('割合') > 1, [set_('割合', 1)]),
        change('力行率', (V('力行目標') - V('力行率')) * V('割合')).c('力行の力は少し遅れて目標に近づく（一次遅れ）'),
        if_else(V('ノッチ') < 0, [
            if_else(eq(V('ノッチ'), -9), [set_('ブレーキ目標', V('非常減速度') / V('常用最大減速度'))],
                    [set_('ブレーキ目標', 0 - V('ノッチ') / 8)]),
        ], [set_('ブレーキ目標', 0)]).c('B1〜B8 で 1/8 ずつ。EB は常用最大より強い'),
        if_(eq(V('ATS状態'), 2), [set_('ブレーキ目標', V('非常減速度') / V('常用最大減速度'))])
        .c('ATS 非常のときは強制的に非常ブレーキ'),
        set_('割合', V('Δt') / V('ブレーキの遅れ')),
        if_(V('割合') > 1, [set_('割合', 1)]),
        change('ブレーキ率', (V('ブレーキ目標') - V('ブレーキ率')) * V('割合'))
        .c('ブレーキシリンダーの空気がたまるまでの遅れ。大人向けポイント: 早めにブレーキを入れよう'),
        set_('BC圧', round_(V('ブレーキ率') * 440)).c('ブレーキシリンダー圧力 [kPa]（計器の表示用）'),
        if_else(V('速度') < V('定出力の速度'), [set_('力行加速度', V('起動加速度'))], [
            if_else(V('速度') < V('特性域の速度'),
                    [set_('力行加速度', V('起動加速度') * V('定出力の速度') / V('速度'))],
                    [set_('力行加速度', V('起動加速度') * V('定出力の速度') * V('特性域の速度') / (V('速度') * V('速度')))]),
        ]).c('速くなるほど加速が弱くなる（定出力域・特性域）'),
        if_(not_(V('速度') < V('最高速度')), [set_('力行加速度', 0)]),
        set_('力行加速度', V('力行加速度') * V('力行率')),
        set_('ブレーキ減速度', V('ブレーキ率') * V('常用最大減速度')),
        if_(V('速度') < 15, [set_('ブレーキ減速度', V('ブレーキ減速度') * (1 + V('低速でのブレーキ増加') * (1 - V('速度') / 15)))])
        .c('止まる直前はブレーキがよく効く。ブレーキを緩めながら止めるとショックが少ない'),
        set_('_c', floor(V('位置') / 10) + 1),
        set_('曲率', item('曲率表', V('_c'))),
        set_('勾配加速度', item('勾配表', V('_c')) * 0.0353).c('1‰ の上り坂で約 0.035 km/h/s ずつ遅くなる'),
        set_('抵抗', V('走行抵抗A') + V('走行抵抗B') * V('速度') * V('速度') + 28 * abs_(V('曲率')))
        .c('走行抵抗＋曲線抵抗（カーブでは少し遅くなる）'),
    ], comment='ノッチから力行の加速度とブレーキの減速度、坂と抵抗を計算する（単位 km/h/s）')

    s.proc('速度と位置を進める', [], [
        if_else(eq(V('ドア'), '開'), [
            set_('速度', 0), set_('加速度', 0),
        ], [
            set_('加速度', V('力行加速度') - V('勾配加速度') - V('抵抗') - V('ブレーキ減速度')),
            set_('前の速度', V('速度')),
            if_(or_(V('速度') > 0, V('加速度') > 0), [
                change('速度', V('加速度') * V('Δt')),
                if_(not_(V('速度') > 0), [
                    set_('速度', 0),
                    if_(V('前の速度') > 0, [
                        set_('停車した', 1),
                        set_('停止時の減速度', 0 - V('加速度')).c('止まった瞬間の減速度。大きいと「ガクン」と止まる'),
                    ]),
                ]).c('速度が 0 を下回ったら止まったことにする（後ろには下がらない）'),
            ]).c('止まっていてブレーキのほうが強いときは動かない'),
            change('位置', (V('前の速度') + V('速度')) / 7.2 * V('Δt')).c('km/h を m/s にするには 3.6 で割る'),
            set_('見た目の曲率', V('曲率') * V('見た目のカーブの強さ')),
            if_(abs_(V('見た目の曲率')) > 1 / V('見た目のカーブの最小半径'), [
                if_else(V('見た目の曲率') > 0, [set_('見た目の曲率', 1 / V('見た目のカーブの最小半径'))],
                        [set_('見た目の曲率', 0 - 1 / V('見た目のカーブの最小半径'))]),
            ]),
            change('方位', V('見た目の曲率') * (V('前の速度') + V('速度')) / 7.2 * V('Δt'))
            .c('カーブで向きが変わった分（遠くの山が流れる）。画面のカーブと合わせて「見た目の曲率」で計算する'),
        ]),
    ], comment='加速度で速度を、速度で位置を進める')

    s.proc('制限を調べる', [], [
        set_('現在の制限', V('路線の最高速度')),
        set_('予告の距離', 99999),
        set_('_i', 1),
        repeat(length('制限の開始'), [
            if_else(and_(item('制限の開始', V('_i')) < V('位置'), item('制限の終了', V('_i')) > V('位置') - V('列車長')), [
                if_(item('制限の速度', V('_i')) < V('現在の制限'), [set_('現在の制限', item('制限の速度', V('_i')))]),
            ], [
                if_(and_(item('制限の開始', V('_i')) > V('位置'),
                         item('制限の開始', V('_i')) - V('位置') < V('予告の距離')), [
                    set_('予告の距離', item('制限の開始', V('_i')) - V('位置')),
                    set_('予告の速度', item('制限の速度', V('_i'))),
                ]).c('まだ入っていない制限のうち一番近いもの（予告）'),
            ]).c('先頭が区間に入ってから、最後尾（列車長だけ後ろ）が抜けるまでが制限'),
            change('_i', 1),
        ]),
    ], comment='いまの制限速度と、次に来る制限（予告）を調べる')

    s.proc('ATSを確かめる', [], [
        if_else(eq(V('ATS状態'), 2), [
            if_(V('速度') < 0.01, [
                change('ATS復帰の時間', V('Δt')),
                if_(V('ATS復帰の時間') > 3, [
                    set_('ATS状態', 0),
                    set_('案内', 'ATS 復帰。ノッチを入れなおして運転を再開'),
                ]),
            ]).c('止まって 3 秒たつと ATS が復帰する'),
        ], [
            if_else(V('速度') > V('現在の制限') + V('ATS非常の余裕'), [
                set_('ATS状態', 2),
                set_('ATS復帰の時間', 0),
                change('ATS非常回数', 1),
                change('区間の減点', V('減点_ATS非常')),
                set_('案内', join('ATS 非常ブレーキ！ 制限 ', V('現在の制限'), ' km/h を大きく超えた')),
                broadcast('ATSベル'),
            ], [
                if_else(V('速度') > V('現在の制限') + V('ATS警報の余裕'), [
                    if_(eq(V('ATS状態'), 0), [
                        set_('ATS状態', 1),
                        change('ATS警報回数', 1),
                        change('区間の減点', V('減点_ATS警報')),
                        set_('案内', join('ATS 警報！ 制限 ', V('現在の制限'), ' km/h まで落とせ')),
                        broadcast('ATSベル'),
                    ]),
                ], [
                    if_(eq(V('ATS状態'), 1), [set_('ATS状態', 0), set_('案内', 'ATS 警報解除')]),
                ]),
            ]),
        ]),
    ], comment='【ATS（自動列車停止装置）】\n制限＋警報の余裕を超えるとベル（減点）、\n'
               '制限＋非常の余裕を超えると非常ブレーキで止められる（大きく減点）。余裕と減点は設定スプライトで変えられる')
    s.proc('ブレーキの案内', [], [
        set_('_d', item('駅の位置', V('次の駅番号')) - V('位置')),
        if_else(V('_d') > 1, [set_('必要減速度', V('速度') * V('速度') / (7.2 * V('_d')))], [set_('必要減速度', 0)])
        .c('次の停止位置にぴったり止まるのに必要な減速度 [km/h/s] ＝ 速度² ÷（7.2 × 距離）'),
        if_(and_(V('予告の速度') < V('速度'), V('予告の距離') < 20000), [
            set_('_a', (V('速度') * V('速度') - V('予告の速度') * V('予告の速度')) / (7.2 * (V('予告の距離') + 1))),
            if_(V('_a') > V('必要減速度'), [set_('必要減速度', V('_a'))]),
        ]).c('次の制限速度に間に合わせるのに必要な減速度'),
        if_else(and_(V('必要減速度') > V('ブレーキ案内の減速度'), not_(V('ノッチ') < 0), eq(V('場面'), '運転中')), [
            if_(eq(V('案内の段階'), 0), [
                set_('案内の段階', 1),
                set_('案内', join('そろそろブレーキ！（必要な減速 ', round_(V('必要減速度') * 10) / 10, ' km/h/s）')),
            ]),
        ], [
            if_(V('必要減速度') < V('ブレーキ案内の減速度') * 0.6, [set_('案内の段階', 0)]),
        ]),
    ], comment='【ブレーキの目安】350km/h からは止まるまでに 4km 以上かかる。\n'
               '間に合わなくなりそうになったら「そろそろブレーキ」と案内する（設定の「ブレーキ案内の減速度」）')
    s.proc('音のきっかけ', [], [
        if_(floor(V('位置') / 25) > V('ジョイント番号'), [
            set_('ジョイント番号', floor(V('位置') / 25)),
            broadcast('ジョイント'),
        ]).c('25m ごと（レール 1 本ごと）に「タタン」'),
    ], comment='走った距離に合わせて音を鳴らす合図を出す')
    s.x, s.y = -50, 150


def build_scoring(p):
    s = p.sprite('採点')
    s.costume_svg('採点', *assets.icon('採点', '#e0a020'))
    s.overview = ('【採点スプライト】駅に止まったかを判定し、採点・ドアの開け閉め・発車を担当。\n'
                  '■ 1駅 100点満点（＋ピタ停車ボーナス 10点）\n'
                  '  停止位置 40点: 停止位置からのずれ（cm）。「停止位置_満点の範囲」以内なら満点、「停止位置_0点の距離」で 0点\n'
                  '  時刻 20点: 定刻（到着時刻）との差。「定時の許容」以内なら満点。遅れ・早着は秒数に応じて少しずつ減点\n'
                  '  停車の衝動 20点: 止まった瞬間の減速度。止まる直前にブレーキを緩めると満点をとりやすい\n'
                  '  運転操作 20点: ATS 警報・ATS 非常・非常ブレーキ・再停車・駅間停車で減点\n'
                  '  大きく行き過ぎた（オーバーラン限度）ときは停車失敗で、運転操作の点だけ\n'
                  '■ きびしさの数値はすべて「設定」スプライトの「採点のきびしさ」にまとめてある（大きくするとやさしくなる）。\n'
                  '■ 点数の付け方そのものを変えたいときは『採点する』を書き換えてください。')
    for n in ('残り', '誤差', '到着差', '停止点', '定時点', '衝動点', '運転点', 'ボーナス', '駅の得点', '誤差の文字', '時間の文字',
              '運転の文字', '発車時刻', '_e', '_d', '通過を調べた駅', 'メロディの時刻'):
        s.var(n, 0)
    s.script(when_recv('判定'), [call('駅の判定'), call('通過駅の案内')], comment='毎フレーム、物理の計算のあとに届く')
    s.proc('次の停車駅へ', [], [
        change('次の駅番号', 1),
        repeat_until(or_(eq(item('駅の種別', V('次の駅番号')), '停車'), not_(V('次の駅番号') < length('駅名'))), [
            change('次の駅番号', 1),
        ]).c('「通過」の駅はとばす'),
    ], comment='「次の駅」を、次に止まる駅にする')
    s.proc('通過駅の案内', [], [
        if_(V('通過を調べた駅') < length('駅名'), [
            if_(V('位置') > item('駅の位置', V('通過を調べた駅') + 1), [
                change('通過を調べた駅', 1),
                if_(eq(item('駅の種別', V('通過を調べた駅')), '通過'), [
                    set_('案内', join(item('駅名', V('通過を調べた駅')), ' 通過')),
                ]),
            ]),
        ]),
    ], comment='通過駅を通り過ぎたら「○○ 通過」と案内する')
