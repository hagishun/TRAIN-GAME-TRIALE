    st.overview = OVERVIEW
    fog_of_sky = {r['sky']: r['colors']['霧'] for r in ROUTES}
    for kind in ('夕方', '昼', '霧', '黒'):
        st.costume_svg(kind, assets.backdrop(kind, fog_of_sky.get(kind, '#000')), 240, 180)
    for name, val, _ in SETTINGS:
        st.var(name, val)
    for name in CAR_VARS + ROUTE_VARS + STATE_VARS:
        st.var(name, 0)
    for name in HUD_VARS:
        st.var(name, '')
    st.lst('16進数', list('0123456789abcdef'))
    st.lst('ノッチの名前', assets.NOTCHES)
    for name in ROUTE_LISTS + ['路線一覧', '車両一覧', '成績', '採点', '横ずれ表', '対向列車_車体色', '対向列車_帯色', '隠れ表',
                               '前の沿線物_左', '前の沿線物_右']:
        st.lst(name)
