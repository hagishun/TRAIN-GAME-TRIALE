    s.proc('アクシデントを描く', [], [
        set_('点滅', floor(timer() * 2.5) % 2),
        if_(V('信号の位置') > V('位置') + 2.5, [
            call('貼る %s 前に %s m 横 %s m', join('信号_', V('信号の色')), V('信号の位置') - V('位置'), -2.7),
            if_else(eq(V('信号の色'), '赤'), [pen_color('#ff3030')], [pen_color('#30ff80')]),
            call('光る点 前に %s m 横 %s m 高さ %s m', V('信号の位置') - V('位置'), -2.7, 5.4),
        ]),
        if_(V('特発の位置') > V('位置') + 2.5, [
            if_else(eq(V('点滅'), 0), [
                call('貼る %s 前に %s m 横 %s m', '特発_点灯', V('特発の位置') - V('位置'), -3.2),
                pen_color('#ff3030'),
                call('光る点 前に %s m 横 %s m 高さ %s m', V('特発の位置') - V('位置'), -3.2, 4.2),
            ], [call('貼る %s 前に %s m 横 %s m', '特発_消灯', V('特発の位置') - V('位置'), -3.2)]),
        ]).c('特殊信号発光機（赤く点滅）。遠くからでも見えるように光の点を重ねる'),
        if_(V('障害物の位置') > V('位置') + 2.5, [
            if_(eq(V('種類'), '踏切の車'), [
                call('貼る %s 前に %s m 横 %s m', join('踏切_', V('点滅') + 1), V('障害物の位置') - V('位置'), -3.2),
                call('貼る %s 前に %s m 横 %s m', join('踏切_', 2 - V('点滅')), V('障害物の位置') - V('位置'), V('線路の間隔') + 3.2),
            ]).c('踏切の警報機（左右）'),
            call('貼る %s 前に %s m 横 %s m', V('絵'), V('障害物の位置') - V('位置'), 0),
        ]),
        if_(and_(not_(eq(V('効果'), '')), V('位置') > V('規制の始め') - 1500), [call('雨や風を描く')]),
    ], comment='信号機・特発・障害物（踏切）と、雨や風を描く')
    s.proc('貼る %s 前に %s m 横 %s m', ['名前', 'z', '横'], [
        if_(V('最大描画距離') > A('z'), [
            call('位置を計算 前に %s m 横 %s m 高さ %s m', A('z'), A('横'), 0),
            if_(and_(abs_(V('画面x')) - 4 * V('倍率') < 240, V('画面y') < 175, eq(V('隠れ'), 0)), [
                costume(A('名前')),
                set_size(V('倍率') * 5),
                set_effect('GHOST', fog_amount(A('z')) * 70),
                goto(V('画面x'), V('画面y')),
                stamp(),
            ]),
        ]),
        costume('ペン用'), set_size(100), clear_effects(),
    ], comment='コスチュームを前方 z m・横の所に立ててスタンプする（20px = 1m の絵）')
    s.proc('光る点 前に %s m 横 %s m 高さ %s m', ['z', '横', '高さ'], [
        if_(V('最大描画距離') > A('z'), [
            call('位置を計算 前に %s m 横 %s m 高さ %s m', A('z'), A('横'), A('高さ')),
            if_(and_(abs_(V('画面x')) < 240, V('画面y') < 180, eq(V('隠れ'), 0)), [
                pen_param('transparency', 45),
                pen_size(V('倍率') * 1.6 + 6),
                goto(V('画面x'), V('画面y')), pen_down(), pen_up(),
                pen_param('transparency', 0),
                pen_size(V('倍率') * 0.6 + 3),
                goto(V('画面x'), V('画面y')), pen_down(), pen_up(),
            ]),
        ]),
    ], comment='信号や特発の光を、遠くからでも見える大きさの点で描く（色は先に決めておく）')
    s.proc('雨や風を描く', [], [
        if_else(eq(V('効果'), '雨'), [pen_color('#d6dee8')], [pen_color('#e8dcc0')]),
        pen_param('transparency', 45),
        pen_size(1.3),
        repeat(36, [
            set_('_x', random(-240, 240)),
            set_('_y', random(-60, 175)),
            goto(V('_x'), V('_y')), pen_down(),
            if_else(eq(V('効果'), '雨'), [goto(V('_x') - 5, V('_y') - 24)], [goto(V('_x') + 38, V('_y') - 6)])
            .c('雨は上から下へ、風は横に流れる線'),
            pen_up(),
        ]),
        pen_param('transparency', 0),
    ], comment='雨や強風の線を、毎フレームでたらめな場所に描く（窓の外の天気）')
    s.x, s.y = 0, 0
