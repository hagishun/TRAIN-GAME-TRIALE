"""アクシデント（ときどきランダムに起きるトラブル）のスプライト。"""
import assets
from sb3 import *
from sprites.common import add_projection, fog_amount

# 種類 → (設定の ON/OFF の変数, 系統)
TYPES = {
    '倒木': ('アクシデント_倒木', '障害物'),
    '落石': ('アクシデント_落石', '障害物'),
    '動物': ('アクシデント_動物', '障害物'),
    '踏切': ('アクシデント_踏切', '障害物'),
    '信号故障': ('アクシデント_信号故障', '設備'),
    '強風': ('アクシデント_強風', '天気'),
    '大雨': ('アクシデント_大雨', '天気'),
    'モーター不調': ('アクシデント_モーター不調', '車両'),
    '非常通報': ('アクシデント_非常通報', '車両'),
}
STOP_TYPES = ['倒木', '落石', '動物', '踏切', '信号故障', '非常通報']

# 知らせるときの案内（{km} は距離に置きかえる）
START_MSG = {
    '倒木': ('防護無線を受信！ ', ' 先で倒木が線路をふさいでいます。手前で止まれ！'),
    '落石': ('落石の知らせ！ ', ' 先の線路に岩が落ちています。手前で止まれ！'),
    '動物': ('前方の線路に動物（シカ）がいます！ ', ' 先。手前で止まれ！'),
    '踏切': ('踏切支障！ ', ' 先の踏切で車が立ち往生しています。手前で止まれ！'),
    '信号故障': ('信号故障の知らせ！ ', ' 先の信号が赤のままです。信号の手前で止まれ！'),
}
OK_MSG = {
    '倒木': '倒木の手前で止まりました。保線係員が木を片づけています…',
    '落石': '岩の手前で止まりました。保線係員が岩を取りのぞいています…',
    '動物': '動物の手前で止まりました。警笛でシカを追いはらっています…',
    '踏切': '踏切の手前で止まりました。車が踏切から出るのを待っています…',
    '信号故障': '赤信号の手前で止まりました。指令と連絡しています…',
    '非常通報': '止まりました。車掌がお客さまのところへ確認に行っています…',
}
NG_MSG = {
    '倒木': '倒木に接触！ 非常ブレーキで止まります（減点）',
    '落石': '岩に接触！ 非常ブレーキで止まります（減点）',
    '動物': 'シカがぎりぎりで逃げました。危なかった！ 非常ブレーキ（減点）',
    '踏切': '踏切の車がぎりぎりで脱出しました。危なかった！ 非常ブレーキ（減点）',
    '信号故障': '赤信号を越えてしまいました！ 非常ブレーキ（減点）',
    '非常通報': '止まるのが遅すぎます！ 非常ブレーキ（減点）',
}
SCORE_TEXT = {
    '倒木': '倒木', '落石': '落石', '動物': '線路の動物', '踏切': '踏切の車', '信号故障': '赤信号', '非常通報': '非常通報',
}
# うまく止まれたときの採点の文字
OK_TEXT = {
    '倒木': '倒木の手前で停止', '落石': '落石の手前で停止', '動物': '線路の動物の手前で停止', '踏切': '踏切の手前で停止',
    '信号故障': '赤信号の手前で停止', '非常通報': '非常通報ですぐに停止',
}


def build_accident(p):
    s = p.sprite('アクシデント')
    s.costume_svg('ペン用', *assets.pen_canvas())
    for name in assets.ACCIDENT_COSTUMES:
        s.costume_svg(name, *assets.accident_costume(name))
    s.overview = ('【アクシデントスプライト】運転中にときどきランダムに起きるトラブル。起こす・進める・描くを担当する。\n'
                  '■ 種類（3 つの系統）\n'
                  '   線路の障害物: 倒木・落石・動物（シカ）・踏切で立ち往生した車 → 手前で止まる\n'
                  '   天気や設備: 強風・大雨（しばらく速度規制）、信号故障（赤信号の手前で止まる）\n'
                  '   車両や車内: モーター不調（次の駅まで加速が弱い）、非常通報（すぐに止まる）\n'
                  '■ 起きやすさ・種類ごとの ON/OFF・点数・規制の速さは「設定」スプライトの「アクシデント」。\n'
                  '   どの種類が起きやすいかは路線ごとに「路線データ」の『アクシデントの候補』で決める（神社線は倒木や動物など）。\n'
                  '■ 流れ: 運転を始めるときに、起きる場所（予定）を決めておく → その場所を通ると起きる →\n'
                  '   案内・警報音・異常表示灯で知らせる → うまく対応できたらボーナス、できなかったら減点（次の駅の得点に入る）。\n'
                  '   350km/h でも止まれるように、止まれる距離より遠くから知らせる（設定の「アクシデント_予告の余裕」）。\n'
                  '   次の駅に近すぎるときは、その駅のあとに延期する。\n'
                  '■ ぶつかっても大事故にはしない（非常ブレーキで止まって減点だけ。動物や車はぎりぎりで逃げる）。\n'
                  '■ アクシデントで遅れた時間は、次の駅の「時刻」の採点で差し引く（変数「遅れの免除」）。\n'
                  '■ 運転スプライトは「止まる位置」「非常停止中」「力行の倍率」を、採点スプライトは「アクシデント点」を見る。')
    for n in ('種類', '_k', '_d', '_t', '必要な距離', '次の停車位置', '始まりの時刻', '待つ時間', '守れた', '規制の始め',
              '規制の終わり', '規制の速度', '案内の区切り', '見つかった', '_x', '_y', '_s', '名前', '越えてはいけない位置'):
        s.var(n, 0)
    for n in ('予定の位置', '予定の種類'):
        s.lst(n)
    add_projection(s)

    # ------------------------------------------------------------ 準備（予定を決める）
    s.script(when_recv('運転の準備'), [call('アクシデントの準備')], comment='運転を始めるときに 1 回')
    s.proc('アクシデントの準備', [], [
        hide(), pen_up(), costume('ペン用'), set_size(100), clear_effects(), point(90),
        set_('アクシデント', '').c('いま起きているアクシデントの種類（空なら何も起きていない）'),
        set_('アクシデントの段階', ''),
        set_('止まる位置', 0).c('ここより手前で止まらないといけない位置 [m]（0 なら無し）'),
        set_('非常停止中', 0), set_('力行の倍率', 1), set_('障害物', ''), set_('天気', ''),
        set_('アクシデント点', 0), set_('アクシデントの文字', ''), set_('遅れの免除', 0),
        delete_all('予定の位置'), delete_all('予定の種類'),
        repeat(V('アクシデント_最大件数'), [
            if_(not_(random(1, 100) > V('アクシデント_起きやすさ')), [
                call('種類を選ぶ'),
                if_(not_(eq(V('種類'), '')), [
                    call('起きる場所を決める'),
                    if_(V('_d') > 0, [add('予定の位置', V('_d')), add('予定の種類', V('種類'))]),
                ]),
            ]).c('「起きやすさ」% の確率で 1 件起きることにする'),
        ]).c('「最大件数」回くり返す → 0〜最大件数のアクシデントが起きる'),
    ], comment='アクシデントの予定（どこで・何が起きるか）を決める')
    enabled_checks = [if_(and_(eq(V('_t'), t), eq(V(var), 1)), [set_('種類', t)]) for t, (var, _) in TYPES.items()]
    s.proc('種類を選ぶ', [], [
        set_('種類', ''),
        if_(length('アクシデントの候補') > 0, [
            set_('_k', 0),
            repeat_until(or_(not_(eq(V('種類'), '')), V('_k') > 30), [
                set_('_t', item('アクシデントの候補', random(1, length('アクシデントの候補')))),
            ] + enabled_checks + [
                change('_k', 1),
            ]).c('路線の候補からでたらめに選んで、設定で ON（1）になっている種類なら決まり'),
        ]),
    ], comment='起きるアクシデントの種類を選んで「種類」に入れる（選べなかったら空）')
    s.proc('起きる場所を決める', [], [
        set_('_k', 0),
        set_('見つかった', 0),
        repeat_until(or_(eq(V('見つかった'), 1), V('_k') > 20), [
            set_('_d', random(item('駅の位置', 1) + 1500, item('駅の位置', length('駅の位置')) - 2500)),
            set_('見つかった', 1),
            set_('_x', 1),
            repeat(length('予定の位置'), [
                if_(abs_(item('予定の位置', V('_x')) - V('_d')) < 5000, [set_('見つかった', 0)]),
                change('_x', 1),
            ]).c('ほかのアクシデントと 5km 以上はなす'),
            change('_k', 1),
        ]),
        if_(eq(V('見つかった'), 0), [set_('_d', 0)]),
    ], comment='始発駅の 1.5km 先から終点の 2.5km 手前までのどこかに、起きる場所「_d」を決める')

    # ------------------------------------------------------------ 毎フレーム
    s.script(when_recv('アクシデント'), [call('アクシデントを進める')],
             comment='毎フレーム（物理のあと、判定の前）。ゲーム進行スプライトの運転ループから届く')
    s.proc('アクシデントを進める', [], [
        if_else(eq(V('アクシデント'), ''), [
            if_(eq(V('場面'), '運転中'), [call('予定を調べる')]),
        ], [
            if_(list_has('止まるアクシデント', V('アクシデント')), [call('止まるアクシデントを進める')]),
            if_(or_(eq(V('アクシデント'), '強風'), eq(V('アクシデント'), '大雨')), [call('規制のアクシデントを進める')]),
        ]).c('モーター不調は、次の駅で採点スプライトが終わらせる'),
        call('障害物を動かす'),
    ], comment='起きる場所に来たらアクシデントを始め、起きているアクシデントを進める')
    s.lst('止まるアクシデント', STOP_TYPES)
    s.proc('予定を調べる', [], [
        set_('_k', 1),
        repeat_until(or_(V('_k') > length('予定の位置'), not_(eq(V('アクシデント'), ''))), [
            if_else(V('位置') > item('予定の位置', V('_k')), [
                set_('種類', item('予定の種類', V('_k'))),
                delete_at('予定の位置', V('_k')), delete_at('予定の種類', V('_k')),
                call('アクシデントを始める'),
            ], [change('_k', 1)]),
        ]),
    ], comment='予定の場所を通りすぎたら、そのアクシデントを始める')
    s.proc('延期する', [], [
        if_(V('次の駅番号') < length('駅名'), [
            add('予定の位置', V('次の停車位置') + 1000), add('予定の種類', V('種類')),
        ]).c('終点の手前なら、やめる'),
    ], comment='次の駅に近すぎて止まる距離が足りないので、次の駅を出たあとに延期する')

    def start_branch(t):
        if t in START_MSG:
            a, b = START_MSG[t]
            km = round_(V('必要な距離') / 100) / 10
            obj = '信号' if t == '信号故障' else t
            return if_(eq(V('種類'), t), [
                set_('障害物', obj),
                set_('障害物の位置', V('位置') + V('必要な距離')),
                set_('障害物の横', -2.4 if t == '信号故障' else 0),
                set_('障害物の状態', '赤' if t == '信号故障' else 'あり'),
                set_('止まる位置', V('障害物の位置') - (10 if t == '信号故障' else 15))
                .c('運転士（とボット）が止まるめやすの位置'),
                set_('越えてはいけない位置', V('障害物の位置') - (0 if t == '信号故障' else 4))
                .c('ここを越えたら「ぶつかった」「赤信号を越えた」'),
                set_('案内', join(a, km, ' km', b)),
                broadcast('防護無線'),
            ])
        if t == '非常通報':
            return if_(eq(V('種類'), t), [
                set_('止まる位置', V('位置') + V('必要な距離')).c('ここまでに止まればよい'),
                set_('越えてはいけない位置', V('止まる位置')),
                set_('案内', join('車内で非常通報！ すぐにブレーキをかけて ', round_(V('必要な距離') / 100) / 10,
                                 ' km 以内に止まれ！')),
                broadcast('非常通報'),
            ])
        if t in ('強風', '大雨'):
            speed_var = '強風の規制速度' if t == '強風' else '大雨の規制速度'
            return if_(eq(V('種類'), t), [
                set_('規制の速度', V(speed_var)),
                set_('_d', (V('速度') * V('速度') - V('規制の速度') * V('規制の速度')) / (7.2 * 2.5)),
                if_(V('_d') < 0, [set_('_d', 0)]),
                set_('規制の始め', round_(V('位置') + V('_d') + 600)).c('いまの速度から 2.5km/h/s で落とせる距離 ＋ 600m 先から'),
                set_('規制の終わり', V('規制の始め') + V('規制区間の長さ')),
                if_(V('規制の終わり') > item('駅の位置', length('駅の位置')) - V('列車長') - 100, [
                    set_('規制の終わり', item('駅の位置', length('駅の位置')) - V('列車長') - 100),
                ]).c('規制区間は終点の手前で終わるようにする（終点に着く前に、守れたかどうかを決めるため）'),
                add('制限の開始', V('規制の始め')), add('制限の終了', V('規制の終わり')), add('制限の速度', V('規制の速度'))
                .c('ふつうの速度制限として足す → ATS・TIMS の予告・制限標識がそのまま使える'),
                broadcast('標識を作り直す'),
                set_('天気', t),
                set_('守れた', 1),
                set_('案内', join(t, 'のため、', round_((V('規制の始め') - V('位置')) / 100) / 10, ' km 先から ',
                                 round_((V('規制の終わり') - V('規制の始め')) / 100) / 10, ' km は ', V('規制の速度'), ' km/h 規制')),
                broadcast('防護無線'),
            ])
        if t == 'モーター不調':
            return if_(eq(V('種類'), t), [
                set_('力行の倍率', V('モーター不調の力') / 100).c('運転スプライトが力行の力にかける'),
                set_('案内', join('モーター不調！ 力行の力が ', V('モーター不調の力'), '% になりました。次の駅まで慎重に')),
                broadcast('防護無線'),
            ])
        raise KeyError(t)

    s.proc('アクシデントを始める', [], [
        set_('次の停車位置', item('駅の位置', V('次の駅番号'))),
        set_('必要な距離', round_(V('速度') * V('速度') / (7.2 * V('常用最大減速度') * 0.6) + V('速度') / 3.6 * 4
                                 + V('アクシデント_予告の余裕')))
        .c('いまの速度から B5 くらい（常用最大の 6 割）で止まれる距離 ＋ 4 秒分 ＋ 余裕。350km/h なら約 5km'),
        if_(and_(list_has('止まるアクシデント', V('種類')),
                 V('位置') + V('必要な距離') + 300 > V('次の停車位置') - V('ホームの長さ')), [
            call('延期する'), stop('this script'),
        ]).c('止まる場所が次の駅にかかるときは延期'),
        if_(and_(eq(V('種類'), 'モーター不調'), V('次の停車位置') - V('位置') < 2500), [call('延期する'), stop('this script')]),
        if_(and_(or_(eq(V('種類'), '強風'), eq(V('種類'), '大雨')),
                 item('駅の位置', length('駅の位置')) - V('位置') < 4000), [stop('this script')])
        .c('終点の近くでは天気の規制は起こさない（規制区間が短すぎる）'),
        set_('アクシデント', V('種類')),
        set_('アクシデントの段階', '知らせた'),
        set_('始まりの時刻', V('時刻の秒')),
        set_('待つ時間', 0),
    ] + [start_branch(t) for t in TYPES] + [
        set_('案内の区切り', floor((V('止まる位置') - V('位置')) / 1000)).c('最初の案内をすぐに書きかえないように'),
    ], comment='アクシデントを 1 つ始める（種類ごとに、障害物を置く・規制を足す・力を弱くする）')

    def stop_fail_branch(t):
        z = V('障害物の位置') - V('位置')
        cant_stop = or_(and_(z < 150, z > 8, V('速度') * V('速度') / (7.2 * (z - 8)) > V('非常減速度')),
                        and_(z < 8.5, V('速度') > 0.5))
        cond = cant_stop if t in ('動物', '踏切') else V('位置') > V('越えてはいけない位置')
        body = [
            set_('案内', NG_MSG[t]),
            change('アクシデント点', 0 - V('アクシデント_減点')),
            set_('アクシデントの文字', join(SCORE_TEXT[t], 'の手前で止まれなかった −', V('アクシデント_減点'))),
            set_('非常停止中', 1).c('運転スプライトが非常ブレーキをかける'),
            set_('止まる位置', V('位置') + 99999).c('止まるまで、駅間停車などの減点はしない'),
            set_('アクシデントの段階', '非常停止'),
        ]
        if t in ('倒木', '落石'):
            body = [broadcast('ドン'), set_('障害物の状態', '消えた').c('はねのけた（残酷な場面にはしない）')] + body
        if t in ('動物', '踏切'):
            body = [set_('障害物の状態', '逃げる').c('ぎりぎりで逃げる（ぶつからない）')] + body
        return if_(and_(eq(V('アクシデント'), t), eq(V('アクシデントの段階'), '知らせた'), cond), body).c(
            '動物と踏切の車は、非常ブレーキでも間に合わないとわかった時点で逃げる（ぶつからない）' if t in ('動物', '踏切')
            else 'ここを越えたら失敗（減点して非常ブレーキ）')

    s.proc('止まるアクシデントを進める', [], [
        if_(eq(V('アクシデントの段階'), '知らせた'), [
            if_(and_(V('速度') > 1, not_(eq(floor((V('止まる位置') - V('位置')) / 1000), V('案内の区切り')))), [
                set_('案内の区切り', floor((V('止まる位置') - V('位置')) / 1000)),
                if_(V('案内の区切り') > -1, [
                    set_('案内', join('⚠ ', item('止まるアクシデントの名前', index_of('止まるアクシデント', V('アクシデント'))),
                                     ' まで あと ', round_((V('止まる位置') - V('位置')) / 100) / 10, ' km　止まれ！')),
                ]),
            ]).c('1km ごとに、あとどれだけで止まらないといけないかを案内する'),
            if_(and_(V('速度') < 0.1, V('位置') < V('越えてはいけない位置')), [
                set_('アクシデントの段階', '待つ'),
                set_('待つ時間', 0),
                change('アクシデント点', V('アクシデント_ボーナス')),
                set_('アクシデントの文字', join(item('うまく止まれたときの文字', index_of('止まるアクシデント', V('アクシデント'))),
                                             ' +', V('アクシデント_ボーナス'))),
            ] + [if_(eq(V('アクシデント'), t), [set_('案内', OK_MSG[t])]) for t in STOP_TYPES])
            .c('障害物・赤信号の手前（非常通報は止まる位置まで）で止まれたら成功（ボーナス）'),
        ] + [stop_fail_branch(t) for t in STOP_TYPES]),
        if_(and_(eq(V('アクシデントの段階'), '非常停止'), V('速度') < 0.1), [
            set_('アクシデントの段階', '待つ'),
            set_('待つ時間', 0),
            set_('案内', '停止しました。車両と線路を点検しています…'),
        ]),
        if_(eq(V('アクシデントの段階'), '待つ'), [
            change('待つ時間', V('Δt')),
            if_(V('待つ時間') > V('アクシデント_待つ時間'), [call('アクシデントを終える')]),
        ]),
    ], comment='障害物・信号故障・非常通報: 止まる位置の手前で止まれたか、止まれなかったかを調べる')
    s.lst('光で知らせる障害物', ['倒木', '落石', '動物', '踏切'])
    s.lst('止まるアクシデントの名前', [SCORE_TEXT[t] for t in STOP_TYPES])
    s.lst('うまく止まれたときの文字', [OK_TEXT[t] for t in STOP_TYPES])
    s.proc('アクシデントを終える', [], [
        change('遅れの免除', V('時刻の秒') - V('始まりの時刻') + 20).c('止まっていた時間と、加速しなおす時間（20秒）は遅れにしない'),
        if_(eq(V('障害物の状態'), 'あり'), [set_('障害物の状態', '消えた')]).c('片づけ終わった'),
        if_(eq(V('障害物'), '信号'), [set_('障害物の状態', '注意')]).c('信号が「注意」（黄色）に変わる'),
        if_(eq(V('障害物'), '踏切'), [set_('障害物の状態', '消えた')]).c('車は踏切から出た（踏切は残る）'),
        set_('非常停止中', 0),
        set_('止まる位置', 0),
        set_('アクシデント', ''),
        set_('アクシデントの段階', ''),
        set_('案内', '安全を確認しました。運転を再開します（↑キー・力行ボタン）'),
    ], comment='片づけ・確認が終わったら、ふつうの運転にもどる')
    s.proc('規制のアクシデントを進める', [], [
        if_(and_(V('位置') > V('規制の始め'), V('位置') - V('列車長') < V('規制の終わり')), [
            if_(eq(V('アクシデントの段階'), '知らせた'), [
                set_('アクシデントの段階', '規制中'),
                set_('案内', join(V('アクシデント'), 'の規制区間に入りました（', V('規制の速度'), ' km/h まで）')),
            ]),
            if_(V('速度') > V('規制の速度') + 3, [set_('守れた', 0)]).c('規制速度を 3km/h より多く超えたら「守れなかった」'),
        ]),
        if_(V('位置') - V('列車長') > V('規制の終わり'), [
            if_else(eq(V('守れた'), 1), [
                change('アクシデント点', V('アクシデント_ボーナス')),
                set_('アクシデントの文字', join(V('アクシデント'), 'の規制を守った +', V('アクシデント_ボーナス'))),
                set_('案内', join(V('アクシデント'), 'の規制区間を抜けました。規制速度を守れました（+', V('アクシデント_ボーナス'), '）')),
            ], [
                change('アクシデント点', 0 - V('アクシデント_減点')),
                set_('アクシデントの文字', join(V('アクシデント'), 'の規制を守れなかった −', V('アクシデント_減点'))),
                set_('案内', join(V('アクシデント'), 'の規制区間を抜けました。規制速度を超えました（−', V('アクシデント_減点'), '）')),
            ]),
            change('遅れの免除', (V('規制の終わり') - V('規制の始め')) * 3.6 * (1 / V('規制の速度') - 1 / V('路線の最高速度')) + 15)
            .c('規制でゆっくり走った分の時間は遅れにしない'),
            set_('天気', ''),
            set_('アクシデント', ''),
            set_('アクシデントの段階', ''),
        ]).c('列車の最後尾が規制区間を抜けたら、守れたかどうかで点数'),
    ], comment='強風・大雨: 規制区間で規制速度を守れたかを調べる')
    s.proc('障害物を動かす', [], [
        if_(eq(V('障害物の状態'), '逃げる'), [
            if_else(eq(V('障害物'), '動物'), [change('障害物の横', 9 * V('Δt'))], [change('障害物の横', -6 * V('Δt'))])
            .c('シカは右へ跳んで、車は左へ走って線路から出る'),
            if_(abs_(V('障害物の横')) > 14, [set_('障害物の状態', '消えた')]),
        ]),
        if_(and_(not_(eq(V('障害物'), '')), V('障害物の位置') - V('位置') < -40), [set_('障害物', '')])
        .c('通りすぎたら描かない'),
        if_(and_(eq(V('障害物の状態'), '消えた'), not_(eq(V('障害物'), '踏切')), not_(eq(V('障害物'), '信号'))),
            [set_('障害物', '')]),
    ], comment='逃げる動物・車を動かし、いらなくなった障害物を消す')

    # ------------------------------------------------------------ 描画
    s.script(when_recv('描画6_アクシデント'), [call('アクシデントを描く')], comment='毎フレーム最後の描画（架線より手前）')
    s.proc('アクシデントを描く', [], [
        if_(not_(eq(V('障害物'), '')), [call('障害物を描く')]),
        if_(eq(V('天気'), '大雨'), [call('雨を描く')]),
        if_(eq(V('天気'), '強風'), [call('風を描く')]),
    ], comment='障害物・信号・踏切と、雨や風')
    s.proc('3Dに貼る %s 前に %s m 横 %s m', ['名前', 'z', '横'], [
        if_(and_(A('z') > 2.5, A('z') < V('最大描画距離')), [
            call('位置を計算 前に %s m 横 %s m 高さ %s m', A('z'), A('横'), 0),
            if_(and_(abs_(V('画面x')) - 4 * V('倍率') < 240, V('画面y') < 180), [
                costume(A('名前')),
                set_size(V('倍率') * 5),
                set_effect('GHOST', fog_amount(A('z')) * 80),
                goto(V('画面x'), V('画面y')),
                stamp(),
            ]),
        ]),
        costume('ペン用'), set_size(100), clear_effects(),
    ], comment='コスチュームを 3D の中（前方 z m、横 m）に立てる')
    s.proc('光る点 前に %s m 横 %s m 高さ %s m 色 %s', ['z', '横', '高さ', '色'], [
        if_(and_(A('z') > 2.5, A('z') < 3000), [
            call('位置を計算 前に %s m 横 %s m 高さ %s m', A('z'), A('横'), A('高さ')),
            if_(and_(abs_(V('画面x')) < 240, V('画面y') < 180), [
                pen_color(A('色')),
                pen_param('transparency', 55),
                pen_size(1.6 * V('倍率') + 6),
                goto(V('画面x'), V('画面y')), pen_down(), pen_up(),
                pen_param('transparency', 0),
                pen_size(0.5 * V('倍率') + 2.5),
                pen_down(), pen_up(),
            ]).c('遠くても 3 ピクセル以上の大きさで光る（まわりのぼんやりした光＋まん中の点）'),
        ]),
    ], comment='3D の中に光る点を描く（障害物を知らせる赤い光・信号の灯り）')
    s.proc('障害物を描く', [], [
        set_('_d', V('障害物の位置') - V('位置')),
        if_(and_(list_has('光で知らせる障害物', V('障害物')), not_(eq(V('障害物の状態'), '消えた')),
                 eq(floor(timer() * 2.5) % 2, 0)), [
            call('光る点 前に %s m 横 %s m 高さ %s m 色 %s', V('_d') + 2, -2.8, 1.2, '#ff2a1a'),
        ]).c('線路わきの赤い光（特殊信号発光機）が点滅して、遠くからでも障害物があるとわかる'),
        if_(eq(V('障害物'), '信号'), [
            if_else(eq(V('障害物の状態'), '赤'), [
                call('光る点 前に %s m 横 %s m 高さ %s m 色 %s', V('_d'), V('障害物の横'), 3.8, '#ff2a1a'),
            ], [call('光る点 前に %s m 横 %s m 高さ %s m 色 %s', V('_d'), V('障害物の横'), 3.4, '#ffb020')]),
        ]).c('信号の灯り'),
        if_(eq(V('障害物'), '踏切'), [
            if_else(eq(floor(timer() * 2.5) % 2, 0), [set_('名前', '踏切_点灯')], [set_('名前', '踏切_消灯')])
            .c('警報灯を交互に点滅させる'),
            call('3Dに貼る %s 前に %s m 横 %s m', V('名前'), V('_d') - 4, -3.4),
            call('3Dに貼る %s 前に %s m 横 %s m', V('名前'), V('_d') + 4, V('線路の間隔') + 3.4),
            if_(not_(eq(V('障害物の状態'), '消えた')), [
                call('3Dに貼る %s 前に %s m 横 %s m', '車', V('_d'), V('障害物の横') + 0.4),
            ]),
        ]),
        if_(eq(V('障害物'), '信号'), [
            call('3Dに貼る %s 前に %s m 横 %s m', join('信号_', V('障害物の状態')), V('_d'), V('障害物の横')),
        ]),
        if_(and_(not_(eq(V('障害物'), '踏切')), not_(eq(V('障害物'), '信号'))), [
            if_(eq(V('障害物の状態'), 'あり'), [call('3Dに貼る %s 前に %s m 横 %s m', V('障害物'), V('_d'), 0)]),
            if_(eq(V('障害物の状態'), '逃げる'), [call('3Dに貼る %s 前に %s m 横 %s m', '動物_跳ぶ', V('_d'), V('障害物の横'))]),
        ]),
    ], comment='線路の上の障害物（倒木・落石・動物）、踏切の警報機と車、信号機を描く。踏切の道は 3D描画スプライトが描く')
    s.proc('雨を描く', [], [
        costume('雨の幕'), set_size(100), set_effect('GHOST', 50), goto(0, 47), stamp().c('窓の向こうを暗くする（半分すきとおった灰色の幕を貼る）'),
        costume('ペン用'), clear_effects(),
        pen_color('#c8d6e4'), pen_param('transparency', 35), pen_size(1),
        repeat(45, [
            set_('_x', random(-240, 240)), set_('_y', random(-60, 155)),
            goto(V('_x'), V('_y')), pen_down(), goto(V('_x') - 3, V('_y') - 13), pen_up(),
        ]).c('雨のすじを毎フレームでたらめな場所に描く → 降っているように見える'),
        pen_param('transparency', 0),
    ], comment='大雨（窓の向こうが暗くなり、雨のすじが降る）')
    s.proc('風を描く', [], [
        pen_color('#ffffff'), pen_param('transparency', 60), pen_size(1),
        repeat(14, [
            set_('_x', random(-260, 200)), set_('_y', random(-50, 150)), set_('_s', random(25, 70)),
            goto(V('_x'), V('_y')), pen_down(), goto(V('_x') + V('_s'), V('_y') - random(0, 5)), pen_up(),
        ]).c('横に流れる風のすじ'),
        pen_param('transparency', 0), pen_color('#7a8a3c'), pen_size(3),
        repeat(6, [goto(random(-240, 240), random(-50, 140)), pen_down(), pen_up()]).c('飛んでくる葉っぱ'),
    ], comment='強風（風のすじと葉っぱ）')
    s.x, s.y = 0, 0
