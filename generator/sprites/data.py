OPPOSING_COLORS = [('#d5dbe1', '#1e5aa8'), ('#e8e1cf', '#c8361f'), ('#cfd6dc', '#2f9a4a'), ('#3a4a5e', '#f39a1e'),
                   ('#e6e9ec', '#7a3fa0')]


def build_settings(p):
    s = p.sprite('設定')
    s.costume_svg('設定', *assets.icon('設定', '#6b7a8f'))
    s.overview = ('【設定スプライト】ゲーム全体の数値をここで決めています。\n'
                  '緑の旗を押すと「設定を読み込む」が送られ、下のブロックが上から順に実行されます。\n'
                  '数字を書き換えるだけで、見え方・難しさ・対向列車の出やすさなどを変えられます。\n'
                  '各ブロックの右のコメントに意味と目安を書いてあります。')
    groups = SETTING_GROUPS
    for title, items in groups:
        body = [set_(n, v).c(c) for n, v, c in items]
        if title == '対向列車':
            body += [
                delete_all('対向列車_車体色').c('対向列車の色の組み合わせ（車体色と帯色を同じ順番で足す）。\n'
                                            '組を増やすと、いろいろな色の対向列車が来るようになる。'),
                delete_all('対向列車_帯色'),
            ]
            for body_c, stripe in OPPOSING_COLORS:
                body += [add('対向列車_車体色', body_c), add('対向列車_帯色', stripe)]
        if title.startswith('空港と飛行機'):
            body.append(delete_all('航空会社の一覧').c('飛んでくる飛行機の航空会社（架空）。景色スプライトに\n'
                                                 '「飛行機_会社名_右」「飛行機_会社名_左」「飛行機_会社名_前」のコスチュームがある会社だけ使える。\n'
                                                 '同じ会社を何回も足すと、その会社の飛行機がよく来る'))
            body += [add('航空会社の一覧', a) for a in assets.AIRLINES]
        s.script(when_recv('設定を読み込む'), body, comment=f'■ {title}')
    s.x, s.y = -200, 150


def build_cars(p):
    s = p.sprite('車両データ')
    s.costume_svg('車両データ', *assets.icon('車両', '#1e5aa8'))
    s.overview = ('【車両データスプライト】運転する電車の性能を決めています。\n'
                  '■ 性能を変える: 下の「T25000系」の定義ブロックの数字を書き換える。\n'
                  '■ 車両を増やす:\n'
                  '  1) 「T25000系」の定義ブロックを複製して名前を変え、数字を変える\n'
                  '  2) 「設定を読み込む」のスクリプトに、車両一覧に足すブロックを 1 つ増やす（メニューに出る説明）\n'
                  '  3) 「車両を読み込む」のスクリプトに「もし 車両番号 = 2 なら」を足して、新しい定義ブロックを呼ぶ\n'
                  '  車両が 2 つ以上になると、路線を選んだあとに車両を選ぶ画面が自動で出ます。\n'
                  '  運転台の見た目は「運転台」スプライトのコスチュームで、車両名と同じ名前のものが使われます。')
    s.script(when_recv('設定を読み込む'), [
        delete_all('車両一覧'),
    ] + [add('車両一覧', c['desc']).c('車両選択メニューに出る説明（この順番が車両番号）') for c in CARS],
        comment='車両選択メニューの中身を作る')
    branches = []
    for i, c in enumerate(CARS):
        branches.append(if_(eq(V('車両番号'), i + 1), [call(c['name'])]))
    s.script(when_recv('車両を読み込む'), branches, comment='選ばれた車両番号の性能を読み込む')
    for c in CARS:
        s.proc(c['name'], [], [
            set_('車両名', c['name']).c('運転台スプライトの同じ名前のコスチュームが使われる'),
            set_('編成両数', c['cars']).c('何両編成か。駅の停止位置目標（停目）の数字にもなる'),
            set_('列車長', V('編成両数') * 20).c('1両 20m。制限速度は最後尾が抜けるまで続く'),
            set_('起動加速度', c['accel']).c('止まった状態から P5 で出せる加速度 [km/h/s]。通勤電車は 2.5〜3.5'),
            set_('定出力の速度', c['const_power']).c('この速度 [km/h] を超えると加速がだんだん弱くなる（モーターの力の限界）'),
            set_('特性域の速度', c['char_speed']).c('この速度 [km/h] を超えるとさらに加速が弱くなる'),
            set_('最高速度', c['max_speed']).c('これ以上は力行しても加速しない [km/h]'),
            set_('常用最大減速度', c['brake_max']).c('B8 のときの減速度 [km/h/s]。B1〜B8 で 1/8 ずつ強くなる'),
            set_('非常減速度', c['brake_eb']).c('非常ブレーキ（EB）の減速度 [km/h/s]'),
            set_('ブレーキの遅れ', c['brake_lag']).c('ブレーキ（BC圧）が効くまでの遅れ [秒]。大きいほど古い電車っぽい'),
            set_('力行の遅れ', c['power_lag']).c('ノッチを入れてから力が出るまでの遅れ [秒]'),
            set_('低速でのブレーキ増加', c['low_speed_gain'])
            .c('止まる直前（15km/h 以下）でブレーキがよく効くようになる割合。\n'
               '本物の電車と同じく、止まる直前にブレーキを緩めないと「ガクン」と止まって減点される'),
            set_('走行抵抗A', c['res_a']).c('何もしなくてもかかる抵抗 [km/h/s]'),
            set_('走行抵抗B', c['res_b']).c('速度の2乗に比例する抵抗（空気抵抗など）。100km/h で A＋B×10000'),
        ], comment=f'【{c["name"]}】{c["desc"]}\nここの数字を変えると電車の性能が変わる。')
    s.x, s.y = -150, 150


def _route_proc(s, idx, r, car):
    tt = timetable(r, car)
    body = [
        call('路線を始める 名前 %s 最高速度 %s km/h', r['name'], r['max_speed'])
        .c('路線の名前と最高速度。最高速度は、制限のない区間の制限速度になる'),
        call('景色 空 %s 遠景 %s 霧の距離 %s m', r['sky'], r['far'], r['fog_dist'])
        .c('空はステージの背景の名前（昼・霧・夕方）、遠景は「景色」スプライトのコスチューム名。\n'
           '霧の距離を小さくすると霧が濃くなる'),
        call('地面の色 %s %s 道床の色 %s %s', r['colors']['地面1'], r['colors']['地面2'], r['colors']['道床1'],
             r['colors']['道床2']).c('地面と道床（線路の砂利）の色。2色を縞にして走っている感じを出す'),
        call('外側の色 左 %s を %s m から 右 %s を %s m から 霧 %s', r['colors']['左外側'], r['left_edge'],
             r['colors']['右外側'], r['right_edge'], r['colors']['霧'])
        .c('線路から離れた所の色（道路・森・海など）と、線路の中心からの距離。霧の色も決める'),
    ]
    for k, (name, pos, t, kind) in enumerate(tt):
        mel = DEPARTURE_MELODY.get(name, 'CLEX202') if kind == '停車' else 'なし'
        b = call('駅を追加 %s 停止位置 %s m 時刻 %s %s 発車メロディ %s', name, pos, t, kind, mel)
        if k == 0:
            b.c('━━ 駅 ━━\n駅名を変えたいときは、ここの駅名を書き換えるだけでよい（表示・成績に使われる）。\n'
                '停止位置は路線の始めからの距離 [m]。時刻は hh:mm:ss（2けた）で、\n'
                '始発駅は発車時刻、2駅目からは到着時刻（定刻）。\n'
                '「停車」「通過」で、その駅に止まるか通過するかを決める（通過の駅は時刻を「通過」と書く）。\n'
                '通過を停車に変えたら、時刻も書くこと（あとの駅の時刻も少し遅らせるとよい）。\n'
                '駅名標の絵は「3D描画」スプライトの、駅名と同じ名前のコスチュームが使われる（無ければ無地）。\n'
                '♪ 最後の「発車メロディ」を書き換えると、その駅を発車するときの曲が変わる（駅ごとの発車メロディ）。\n'
                '   曲は「発車メロディ」スプライトの音の名前（CLEX202 / CLEX203 / CLEX204）。「なし」なら鳴らさない。\n'
                '   曲: Clarinet_Express 様（信町高速鉄道のために制作、許可を得て使用）')
        elif kind == '通過' and tt[k - 1][3] == '停車':
            b.c('通過駅（止まらずに通り過ぎる。速達運転）')
        elif name in TRANSFER:
            b.c(f'{name}: {TRANSFER[name]}（駅名標の下の帯に表示）')
        body.append(b)
    for k, (a, b_, v) in enumerate(r['limits']):
        blk = call('制限を追加 %s m から %s m まで %s km/h', a, b_, v)
        if k == 0:
            blk.c('━━ 速度制限 ━━\n区間の始めと終わり [m] と制限速度。始めに制限標識、終わりに解除標識が立つ。\n'
                  '列車の最後尾が区間を抜けるまで制限が続く')
        body.append(blk)
    for k, (a, ln, rad, side) in enumerate(r['curves']):
        blk = call('カーブを追加 %s m から 長さ %s m 半径 %s m %s', a, ln, rad, side)
        if k == 0:
            blk.c('━━ カーブ ━━\n半径が小さいほど急なカーブ。向きは「右」か「左」。\n'
                  'カーブの制限速度は別に「制限を追加」で決める（目安: 半径300m で 65km/h）')
        body.append(blk)
    for k, (a, ln, g) in enumerate(r['grades']):
        blk = call('勾配を追加 %s m から 長さ %s m %s ‰', a, ln, g)
        if k == 0:
            blk.c('━━ 坂（勾配）━━\n‰（パーミル）は 1000m 進んで何 m 上るか。＋が上り坂、−が下り坂。\n'
                  '上り坂では加速が弱く、下り坂ではブレーキが効きにくい')
        body.append(blk)
    body.append(call('沿線物の間隔を %s m にする', r['scenery_interval'])
                .c('━━ 沿線の景色 ━━\n木や建物を置く間隔。左右に置く物は下の「沿線物を追加」で決める'))
    shop_noted = False
    for side in ('左', '右'):
        for name in r['scenery_left' if side == '左' else 'scenery_right']:
            blk = call('沿線物を追加 %s 側に %s', side, name)
            if name.startswith('店_') and not shop_noted:
                shop_noted = True
                blk.c('━━ 沿線の店 ━━\n「店_」で始まる名前は、看板つきの店（景色スプライトのコスチューム）。\n'
                      'ここを書き換えると、どの店が並ぶかが変わる（ほかの路線の店や、自分で描いた店も使える）。\n'
                      '看板の店名そのものを変えるには、景色スプライトのコスチューム「店_○○」を開いて文字を書き換え、\n'
                      'コスチューム名も「店_新しい店名」に変えてから、ここの名前も同じにする。')
            body.append(blk)
    if not r['scenery_right']:
        body[-1].c('右側には何も置かない（海が見える）') if r['scenery_left'] else None
    for k, name in enumerate(r.get('accidents', [])):
        blk = call('アクシデントの候補 %s', name)
        if k == 0:
            blk.c('━━ この路線で起きやすいアクシデント ━━\n同じ名前を何回も書くと、その種類が起きやすくなる。\n'
                  '名前: 倒木・落石・動物・踏切・強風・大雨・信号故障・モーター不調・非常通報。\n'
                  'どのくらい起きるか・種類ごとの ON/OFF は「設定」スプライトの「アクシデント」')
        body.append(blk)
    if 'airport' in r:
        a, b_, rx = r['airport']
        body.append(call('空港 %s m から %s m まで 滑走路の横 %s m', a, b_, rx)
                    .c('━━ 空港 ━━\n空港の区間（始めと終わり [m]）と、滑走路の中心が線路から何 m 横にあるか（−が左、＋が右）。\n'
                       'この区間では、空港の側に木や店を置かず、エプロン（コンクリート）と滑走路を描く。\n'
                       '飛行機はこの滑走路に着陸・離陸する（出やすさは「設定」スプライトの「空港と飛行機」）'))
        for k, (name, pos, x) in enumerate(r['landmarks']):
            blk = call('目印を追加 %s 位置 %s m 横 %s m', name, pos, x)
            if k == 0:
                blk.c('━━ 空港の建物（目印）━━\n景色スプライトのコスチューム名・位置 [m]・線路からの横の距離 [m]（−が左）。\n'
                      '位置の小さい順に書く（奥の物から順に描くため）。ターミナル・管制塔・格納庫・駐機している飛行機など。\n'
                      '目印は空港でなくても使える（好きな場所に大きな建物を 1 つだけ置きたいときなど）')
            body.append(blk)
    s.proc(f'路線{idx} {r["name"]}', [], body,
           comment=f'【路線{idx}: {r["name"]}（{r["level"]}）】\n{r["note"]}\n'
                   'このブロックの中身を書き換えると路線が変わる。')
    return tt


def build_routes(p):
    s = p.sprite('路線データ')
    s.costume_svg('路線データ', *assets.icon('路線', '#c8361f'))
    s.overview = ('【路線データスプライト】3つの路線の駅・時刻表・制限速度・カーブ・坂・景色を決めています。\n'
                  '路線と駅は「信町高速鉄道 路線図」に合わせています。\n'
                  '■ 駅名を変える: 下の「路線1 信町本線」などの定義の中の「駅を追加」ブロックの駅名を書き換える。\n'
                  '■ 止まる駅・通過する駅: 「駅を追加」の最後を「停車」か「通過」にする（信町本線は速達で 7 駅を通過）。\n'
                  '   （同じ駅が2つの路線にあるとき＝高田・信早ヶ丘は、両方の路線で書き換える）\n'
                  '■ 時刻表を変える: 「駅を追加」の時刻を書き換える（hh:mm:ss）。\n'
                  '■ 路線を増やす:\n'
                  '  1) 「路線3 田原海岸線」の定義を複製して「路線4 ○○線」にし、中身を書き換える\n'
                  '  2) 「設定を読み込む」のスクリプトで路線一覧に説明を 1 行足す（メニューに出る）\n'
                  '  3) 「路線を読み込む」のスクリプトに「もし 路線番号 = 4 なら 路線4 ○○線」を足す\n'
                  '■ 位置はすべて路線の始めからの距離 [m] で書きます。')
    s.var('_i', 0)
    s.var('_a', 0)
    s.var('_b', 0)
    s.var('_c', 0)
    s.var('_m', 0)
    s.var('_r', 0)
    s.var('秒', 0)
    s.var('緩和曲線の長さ', 40)
    s.script(when_recv('設定を読み込む'), [
        delete_all('路線一覧'),
    ] + [add('路線一覧', r['desc']).c('路線選択メニューに出る説明（この順番が路線番号）') if i == 0 else
         add('路線一覧', r['desc']) for i, r in enumerate(ROUTES)] + [
        set_('緩和曲線の長さ', 40).c('カーブの入口と出口で、曲がり方を少しずつ強く・弱くする長さ [m]'),
    ], comment='路線選択メニューの中身を作る')
    branches = [if_(eq(V('路線番号'), i + 1), [call(f'路線{i + 1} {r["name"]}')]) for i, r in enumerate(ROUTES)]
    s.script(when_recv('路線を読み込む'), branches + [call('表を作る')],
             comment='選ばれた路線のデータを読み込み、10m ごとの表を作る')

    tts = []
    for i, r in enumerate(ROUTES):
        tts.append(_route_proc(s, i + 1, r, CARS[0]))
    # データを書き込むブロック
    s.proc('路線を始める 名前 %s 最高速度 %s km/h', ['名前', '最高速度'], [
        set_('路線名', A('名前')),
        set_('路線の最高速度', A('最高速度')),
    ] + [delete_all(n) for n in ('駅名', '駅の位置', '駅の時刻', '駅の種別', '駅の発車メロディ', '制限の開始', '制限の終了', '制限の速度', 'カーブの開始',
                                 'カーブの終了', 'カーブの曲率', '勾配の開始', '勾配の終了', '勾配の値', '沿線物_左', '沿線物_右',
                                 '目印の名前', '目印の位置', '目印の横', 'アクシデントの候補')]
           + [set_('沿線物の間隔', 30), set_('空港の始め', 0), set_('空港の終わり', 0).c('0 のときは空港なし'),
              set_('滑走路の横', 0)], comment='━━ ここから下は、上の路線のブロックで使う部品（ふつうは変えなくてよい）━━\n'
                                                   '路線のデータを空にして、名前と最高速度を決める')
    s.proc('景色 空 %s 遠景 %s 霧の距離 %s m', ['空', '遠景', '霧の距離'], [
        set_('空', A('空')), set_('遠景', A('遠景')), set_('霧の距離', A('霧の距離')),
    ], comment='空（背景の名前）・遠景（景色スプライトのコスチューム名）・霧の距離を決める')
    s.proc('地面の色 %s %s 道床の色 %s %s', ['地面1', '地面2', '道床1', '道床2'], [
        set_('色_地面1', A('地面1')), set_('色_地面2', A('地面2')), set_('色_道床1', A('道床1')),
        set_('色_道床2', A('道床2')),
    ], comment='地面と道床の色（#rrggbb）')
    s.proc('外側の色 左 %s を %s m から 右 %s を %s m から 霧 %s', ['左の色', '左の距離', '右の色', '右の距離', '霧の色'], [
        set_('色_左外側', A('左の色')), set_('左外側の距離', A('左の距離')),
        set_('色_右外側', A('右の色')), set_('右外側の距離', A('右の距離')), set_('色_霧', A('霧の色')),
    ], comment='線路から離れた所の色と距離、霧の色')
    s.proc('駅を追加 %s 停止位置 %s m 時刻 %s %s 発車メロディ %s', ['駅名', '停止位置', '時刻', '停車か通過', '発車メロディ'], [
        add('駅名', A('駅名')), add('駅の位置', A('停止位置')), add('駅の時刻', A('時刻')),
        if_else(eq(A('停車か通過'), '通過'), [add('駅の種別', '通過')], [add('駅の種別', '停車')]),
        add('駅の発車メロディ', A('発車メロディ')).c('この駅を発車するときに「発車メロディ」スプライトが鳴らす曲の名前'),
    ], comment='駅を1つ足す。上から順に、始発駅・2番目の駅…となる。「通過」と書いた駅には止まらない。\n'
               '発車メロディは駅ごとに決められる（ここを変えると駅ごとの発車メロディが変わる）')
    s.proc('制限を追加 %s m から %s m まで %s km/h', ['始め', '終わり', '速度'], [
        add('制限の開始', A('始め')), add('制限の終了', A('終わり')), add('制限の速度', A('速度')),
    ], comment='速度制限の区間を1つ足す')
    s.proc('カーブを追加 %s m から 長さ %s m 半径 %s m %s', ['始め', '長さ', '半径', '向き'], [
        add('カーブの開始', A('始め')),
        add('カーブの終了', A('始め') + A('長さ')),
        if_else(eq(A('向き'), '右'), [add('カーブの曲率', 1 / A('半径'))], [add('カーブの曲率', 0 - 1 / A('半径'))])
        .c('曲率＝1÷半径。右カーブは＋、左カーブは−で覚えておく'),
    ], comment='カーブを1つ足す')
    s.proc('勾配を追加 %s m から 長さ %s m %s ‰', ['始め', '長さ', '勾配'], [
        add('勾配の開始', A('始め')), add('勾配の終了', A('始め') + A('長さ')), add('勾配の値', A('勾配')),
    ], comment='坂を1つ足す（＋上り、−下り）')
    s.proc('沿線物の間隔を %s m にする', ['間隔'], [set_('沿線物の間隔', A('間隔'))],
           comment='木や建物を置く間隔 [m]')
    s.proc('空港 %s m から %s m まで 滑走路の横 %s m', ['始め', '終わり', '滑走路の横'], [
        set_('空港の始め', A('始め')), set_('空港の終わり', A('終わり')), set_('滑走路の横', A('滑走路の横')),
    ], comment='空港の区間と滑走路の位置を決める（1 つの路線に 1 つだけ）')
    s.proc('目印を追加 %s 位置 %s m 横 %s m', ['名前', '位置', '横'], [
        add('目印の名前', A('名前')), add('目印の位置', A('位置')), add('目印の横', A('横')),
    ], comment='決まった場所に建物などを 1 つ置く。名前は「景色」スプライトのコスチューム名')
    s.proc('アクシデントの候補 %s', ['種類'], [add('アクシデントの候補', A('種類'))],
           comment='この路線で起きるかもしれないアクシデントの種類を 1 つ足す')
    s.proc('沿線物を追加 %s 側に %s', ['側', '名前'], [
        if_else(eq(A('側'), '左'), [add('沿線物_左', A('名前'))], [add('沿線物_右', A('名前'))]),
    ], comment='線路の左か右に置く物を足す。名前は「景色」スプライトのコスチューム名。\n'
               '同じ名前を何回も足すと、その物がよく出るようになる')

    # 表を作る
    def fill_table(prefix, table, value_list, ramp):
        inner = [set_('_m', (V('_c') - 1) * 10 + 5).c('10m のマス目の真ん中の位置')]
        if ramp:
            inner.append(if_(and_(V('_m') > V('_a'), V('_m') < V('_b')), [
                set_('_r', (V('_m') - V('_a')) / V('緩和曲線の長さ')),
                if_((V('_b') - V('_m')) / V('緩和曲線の長さ') < V('_r'),
                    [set_('_r', (V('_b') - V('_m')) / V('緩和曲線の長さ'))]),
                if_(V('_r') > 1, [set_('_r', 1)]),
                replace(table, V('_c'), item(value_list, V('_i')) * V('_r'))
                .c('入口と出口では曲率を少しずつ変える（緩和曲線）'),
            ]))
        else:
            inner.append(if_(and_(V('_m') > V('_a'), V('_m') < V('_b')), [
                replace(table, V('_c'), item(value_list, V('_i'))),
            ]))
        inner.append(change('_c', 1))
        return [
            set_('_i', 1),
            repeat(length(f'{prefix}の開始'), [
                set_('_a', item(f'{prefix}の開始', V('_i'))),
                set_('_b', item(f'{prefix}の終了', V('_i'))),
                set_('_c', floor(V('_a') / 10) + 1),
                repeat_until(V('_c') - 1 > V('_b') / 10, inner),
                change('_i', 1),
            ]),
        ]

    s.proc('表を作る', [], [
        set_('終点の位置', item('駅の位置', length('駅の位置')) + 600).c('最後の駅の 600m 先で線路はおしまい'),
        delete_all('曲率表'),
        delete_all('勾配表'),
        repeat(ceil(V('終点の位置') / 10) + 120, [add('曲率表', 0), add('勾配表', 0)])
        .c('10m ごとのマス目を 0 で埋める（終点の先も少し作っておく）'),
    ] + fill_table('カーブ', '曲率表', 'カーブの曲率', True) + fill_table('勾配', '勾配表', '勾配の値', False) + [
        delete_all('駅の時刻秒'),
        set_('_i', 1),
        repeat(length('駅の時刻'), [
            if_else(eq(item('駅の種別', V('_i')), '通過'), [add('駅の時刻秒', 0)], [
                call('時刻を秒にする %s', item('駅の時刻', V('_i'))),
                add('駅の時刻秒', V('秒')),
            ]),
            change('_i', 1),
        ]).c('時刻の文字（hh:mm:ss）を、計算しやすい秒に直しておく（通過駅は 0）'),
    ], comment='カーブと坂のデータから、10m ごとの「曲率表」「勾配表」を作る。\n'
               '3D描画と運転は、この表を見るだけでその場所のカーブと坂がわかる')
    s.proc('時刻を秒にする %s', ['時刻'], [
        set_('秒', join(letter_of(1, A('時刻')), letter_of(2, A('時刻'))) * 3600
             + join(letter_of(4, A('時刻')), letter_of(5, A('時刻'))) * 60
             + join(letter_of(7, A('時刻')), letter_of(8, A('時刻'))))
        .c('"17:30:05" → 17×3600 ＋ 30×60 ＋ 5'),
    ], comment='hh:mm:ss の文字を、1日の始めからの秒にして「秒」に入れる')

    s.x, s.y = -100, 150
    return tts
