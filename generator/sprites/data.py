            set_('列車長', V('編成両数') * 20).c('1両 20m。制限速度は最後尾が抜けるまで続く'),
            set_('起動加速度', c['accel']).c('止まった状態から P5 で出せる加速度 [km/h/s]。通勤電車は 2.5〜3.5'),
            set_('定出力の速度', c['const_power']).c('この速度 [km/h] を超えると加速がだんだん弱くなる（モーターの力の限界）'),
            set_('特性域の速度', c['char_speed']).c('この速度 [km/h] を超えるとさらに加速が弱くなる'),
            set_('最高速度', c['max_speed']).c('これ以上は力行しても加速しない [km/h]'),
            set_('常用最大減速度', c['brake_max']).c('B8 のときの減速度 [km/h/s]。B1〜B8 で 1/8 ずつ強くなる'),
            set_('非常減速度', c['brake_eb']).c('非常ブレーキ（EB）の減速度 [km/h/s]'),
            set_('ブレーキの遅れ', c['brake_lag']).c('ブレーキ（BC圧）が効くまでの遅れ [秒]。大きいほど古い電車っぽい'),
            set_('力行の遅れ', c['power_lag']).c('ノッチを入れてから力が出るまでの遅れ [秒]'),
            set_('低速でのブレーキ増加', c['low_speed_gain'])
