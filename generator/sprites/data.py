def _route_proc(s, idx, r, car):
    tt = timetable(r, car)
    body = [
        call('路線を始める 名前 %s 最高速度 %s km/h', r['name'], r['max_speed'])
        .c('路線の名前と最高速度。最高速度は、制限のない区間の制限速度になる'),
        call('景色 空 %s 遠景 %s 霧の距離 %s m', r['sky'], r['far'], r['fog_dist'])
        .c('空はステージの背景の名前（昼・霧・夕方）、遠景は「景色」スプライトのコスチューム名。\n'
           '霧の距離を小さくすると霧が濃くなる'),
        call('地面の色 %s %s 道床の色 %s %s', r['colors']['地面1'], r['colors']['地面2'], r['colors']['道床1'],
             r['colors']['道床2']).c('地面と道床（線路の砂利）の色。2色を縞にして走っている感じを出す'),
        call('外側の色 左 %s を %s m から 右 %s を %s m から 霧 %s', r['colors']['左外側'], r['left_edge'],
             r['colors']['右外側'], r['right_edge'], r['colors']['霧'])
        .c('線路から離れた所の色（道路・森・海など）と、線路の中心からの距離。霧の色も決める'),
    ]
    for k, (name, pos, t, kind) in enumerate(tt):
        b = call('駅を追加 %s 停止位置 %s m 時刻 %s %s', name, pos, t, kind)
        if k == 0:
            b.c('━━ 駅 ━━\n駅名を変えたいときは、ここの駅名を書き換えるだけでよい（表示・成績に使われる）。\n'
                '停止位置は路線の始めからの距離 [m]。時刻は hh:mm:ss（2けた）で、\n'
                '始発駅は発車時刻、2駅目からは到着時刻（定刻）。\n'
                '最後の「停車」「通過」で、その駅に止まるか通過するかを決める（通過の駅は時刻を「通過」と書く）。\n'
                '通過を停車に変えたら、時刻も書くこと（あとの駅の時刻も少し遅らせるとよい）。\n'
                '駅名標の絵は「3D描画」スプライトの、駅名と同じ名前のコスチュームが使われる（無ければ無地）。')
        elif kind == '通過' and tt[k - 1][3] == '停車':
            b.c('通過駅（止まらずに通り過ぎる。速達運転）')
        elif name in TRANSFER:
            b.c(f'{name}: {TRANSFER[name]}（駅名標の下の帯に表示）')
        body.append(b)
    for k, (a, b_, v) in enumerate(r['limits']):
        blk = call('制限を追加 %s m から %s m まで %s km/h', a, b_, v)
        if k == 0:
            blk.c('━━ 速度制限 ━━\n区間の始めと終わり [m] と制限速度。始めに制限標識、終わりに解除標識が立つ。\n'
                  '列車の最後尾が区間を抜けるまで制限が続く')
        body.append(blk)
    for k, (a, ln, rad, side) in enumerate(r['curves']):
        blk = call('カーブを追加 %s m から 長さ %s m 半径 %s m %s', a, ln, rad, side)
        if k == 0:
            blk.c('━━ カーブ ━━\n半径が小さいほど急なカーブ。向きは「右」か「左」。\n'
                  'カーブの制限速度は別に「制限を追加」で決める（目安: 半径300m で 65km/h）')
        body.append(blk)
    for k, (a, ln, g) in enumerate(r['grades']):
        blk = call('勾配を追加 %s m から 長さ %s m %s ‰', a, ln, g)
        if k == 0:
            blk.c('━━ 坂（勾配）━━\n‰（パーミル）は 1000m 進んで何 m 上るか。＋が上り坂、−が下り坂。\n'
                  '上り坂では加速が弱く、下り坂ではブレーキが効きにくい')
        body.append(blk)
    body.append(call('沿線物の間隔を %s m にする', r['scenery_interval'])
                .c('━━ 沿線の景色 ━━\n木や建物を置く間隔。左右に置く物は下の「沿線物を追加」で決める'))
    shop_noted = False
    for side in ('左', '右'):
        for name in r['scenery_left' if side == '左' else 'scenery_right']:
            blk = call('沿線物を追加 %s 側に %s', side, name)
            if name.startswith('店_') and not shop_noted:
                shop_noted = True
                blk.c('━━ 沿線の店 ━━\n「店_」で始まる名前は、看板つきの店（景色スプライトのコスチューム）。\n'
                      'ここを書き換えると、どの店が並ぶかが変わる（ほかの路線の店や、自分で描いた店も使える）。\n'
                      '看板の店名そのものを変えるには、景色スプライトのコスチューム「店_○○」を開いて文字を書き換え、\n'
                      'コスチューム名も「店_新しい店名」に変えてから、ここの名前も同じにする。')
            body.append(blk)
    if not r['scenery_right']:
        body[-1].c('右側には何も置かない（海が見える）') if r['scenery_left'] else None
    for k, (a, b_, side) in enumerate(r.get('airports', [])):
        blk = call('空港を置く %s m から %s m まで %s 側', a, b_, side)
        if k == 0:
            blk.c('━━ 空港 ━━\n線路のわきに空港（芝生・エプロン・滑走路・誘導灯・ターミナル・管制塔・駐機中の飛行機）を置く。\n'
                  '始めと終わり [m] と、線路の「右」か「左」か。ここを変えると空港の場所が変わる（ほかの路線にも足せる）。\n'
                  '近くを走ると、ときどき飛行機が着陸・離陸する（出やすさは設定スプライトの「空港と飛行機」）。\n'
                  '空港の中の建物の並びは「景色」スプライトの『空港に置く』')
        body.append(blk)
    for k, kind in enumerate(r.get('accidents', [])):
        blk = call('起きるアクシデント %s', kind)
        if k == 0:
            blk.c('━━ アクシデント ━━\nこの路線で、ときどき起きるトラブルの種類。ここを変えると起きるアクシデントが変わる。\n'
                  '書ける種類: 倒木・落石・動物・踏切の車（線路の障害物）／強風・大雨（速度規制）／信号故障（一時停止）／\n'
                  'モーター不調・非常通報（車両や車内）。起きやすさとオン・オフは設定スプライトの「アクシデント」')
        body.append(blk)
    s.proc(f'路線{idx} {r["name"]}', [], body,
           comment=f'【路線{idx}: {r["name"]}（{r["level"]}）】\n{r["note"]}\n'
                   'このブロックの中身を書き換えると路線が変わる。')
    return tt


def _service_proc(s, idx, svc, car):
    tt = service_timetable(svc, car)
    route_no = {r['name']: i + 1 for i, r in enumerate(ROUTES)}
    body = [
        call('運行を始める 種別 %s 行き先 %s', svc['type'], svc['dest'])
        .c('種別（「設定を読み込む」の『種別を追加』にある名前）と行き先（終点の駅名）。\n'
           '両数は種別で決まり、運転中は「' + svc['type'] + ' ' + svc['dest'] + '行」のように表示される'),
    ]
    for k, (rname, a, b) in enumerate(svc['sections']):
        blk = call('区間を足す 路線 %s %s から %s まで', route_no[rname], a, b)
        if k == 0:
            blk.c('━━ 走る区間 ━━\n路線の番号（路線1 信町本線 なら 1）と、その路線のどの駅からどの駅までを走るか。\n'
                  '上から順につながる（前の区間の終わりの駅と、次の区間の始めの駅を同じ駅にする）。\n'
                  '駅・制限・カーブ・坂・空港・アクシデントは、その路線の定義からそのまま持ってくる。\n'
                  '景色（空・遠景・色・沿線物）は、つなぐ駅に着くところで次の路線のものに切り替わる。')
        else:
            blk.c(f'{a}で{rname}に入る（{a}から先は{rname}の景色）')
        body.append(blk)
    first_stop = True
    for name, pos, t, kind in tt:
        if kind != '停車':
            continue
        blk = call('停車 %s 時刻 %s', name, t)
        if first_stop:
            first_stop = False
            blk.c('━━ 停車駅と時刻表 ━━\nここに書いた駅に止まり、書いていない駅は通過する（停車駅のパターン）。\n'
                  '時刻は hh:mm:ss（2けた）で、始発駅は発車時刻、2駅目からは到着時刻（定刻）。\n'
                  '停車駅を足したり消したりしたら、あとの駅の時刻も直すこと（止まる駅が増えるとそのぶん遅くなる）')
        elif name == '信町空港':
            blk.c('信町空港（駅の海側に空港がある）')
        body.append(blk)
    stops = sum(1 for row in tt if row[3] == '停車')
    s.proc(f'運行{idx} {svc["name"]}', [], body,
           comment=f'【運行{idx}: {svc["type"]} {svc["dest"]}行（{svc["level"]}・'
                   f'{next(t["cars"] for t in TRAIN_TYPES if t["name"] == svc["type"])}両・{stops}駅停車）】\n'
                   f'{svc["note"]}\n'
                   '運行＝種別 × 走る区間 × 停車駅。このブロックの中身を書き換えると、区間や停車駅が変わる。')
    return tt


def build_routes(p):
    s = p.sprite('路線データ')
    s.costume_svg('路線データ', *assets.icon('路線', '#c8361f'))
    n_routes = len(ROUTES)
    s.overview = ('【路線データスプライト】3つの路線の駅・時刻表・制限速度・カーブ・坂・景色と、\n'
                  '種別（エアポート特快など）と、種別つきの列車（運行）の走る区間・停車駅を決めています。\n'
                  '路線と駅は「信町高速鉄道 路線図」に合わせています。\n'
                  '■ 駅名を変える: 下の「路線1 信町本線」などの定義の中の「駅を追加」ブロックの駅名を書き換える。\n'
                  '■ 止まる駅・通過する駅: 「駅を追加」の最後を「停車」か「通過」にする（信町本線は速達で 7 駅を通過）。\n'
                  '   （同じ駅が2つの路線にあるとき＝高田・信早ヶ丘は、両方の路線で書き換える）\n'
                  '■ 時刻表を変える: 「駅を追加」の時刻を書き換える（hh:mm:ss）。\n'
                  '■ 路線を増やす:\n'
                  '  1) 「路線3 田原海岸線」の定義を複製して「路線○ ○○線」にし、中身を書き換える（○は路線一覧での番号）\n'
                  '  2) 「設定を読み込む」のスクリプトで路線一覧に説明を 1 行足す（メニューに出る。上からの順番が番号）\n'
                  '  3) 『路線を読む』に「もし 番号 = ○ なら 路線○ ○○線」を足す\n'
                  '■ 種別（列車の種類）と運行（種別つきの列車。例: エアポート特快 田原京行）:\n'
                  '  ・種別は「設定を読み込む」の『種別を追加 名前 両数』で決める（両数が列車の長さになる）。\n'
                  '  ・運行は「運行4 エアポート特快」のような定義で、『運行を始める』（種別と行き先）・『区間を足す』（走る路線と駅）・\n'
                  '    『停車』（止まる駅と時刻）を並べる。区間をつなぐと、駅・制限・カーブ・坂・空港がつながり、\n'
                  '    つなぐ駅から先は次の路線の景色になる。\n'
                  '  ・種別つきの列車を増やす（例: 快速 信早ヶ丘行）:\n'
                  '    1) 新しい種別なら『種別を追加』を 1 つ足す（例: 快速 10両、普通 6両）\n'
                  '    2) 「運行4 エアポート特快」の定義を複製して「運行○ 快速」にし、種別・行き先・区間・停車駅と時刻を書き換える\n'
                  '    3) 路線一覧に説明を 1 行足し、『路線を読む』に「もし 番号 = ○ なら 運行○ 快速」を足す\n'
                  '■ 位置はすべて路線の始めからの距離 [m] で書きます。')
    for n in ('_i', '_a', '_b', '_c', '_m', '_r', '秒', '_駅0', '_制限0', '_カーブ0', '_勾配0', '_空港0', '_事故0',
              '_始め', '_終わり', 'ずらし', '下の端', '区間の最高速度', '景色の番号'):
        s.var(n, 0)
